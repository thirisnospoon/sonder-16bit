#!/usr/bin/env python3
"""
Эталонный вход для свода: записи с известными заранее итогами.

ПОЧЕМУ ФАЙЛ ПОРОЖДАЕТСЯ, А НЕ ЛЕЖИТ ГОТОВЫМ. Запись фиксированной
ширины — 380 байт добивки, из которых значимы единицы. Готовый файл в
репозитории нельзя ни прочитать глазами, ни поправить, не пересчитав
смещения; а главное, он разъехался бы с контрактом молча, потому что
разъезд в файле фиксированной ширины не виден ничем.

Ширины берутся из contracts/reports/digest-v1.yaml — из того же места,
откуда их берут копибук и писатель на Java.

ЧТО ИМЕННО ПРОВЕРЯЮТ ЭТИ ДАННЫЕ, кроме сложения:

  * контрольный переход по автору — три автора подряд;
  * ПОСЛЕДНЮЮ группу. Переход срабатывает на СМЕНЕ автора, а после
    последней записи менять уже нечего: забытый итог последнего автора
    — классическая потеря в этом приёме, и выглядит она как «просто
    одного автора нет», а не как ошибка;
  * автора с одной записью — группа из одного элемента ломается иначе,
    чем группа из многих;
  * кириллицу в теле: байт вдвое больше символов, и итог «байт на
    символ» обязан это показать;
  * чистую латиницу: у неё байты равны символам, и смешение двух видов
    в одном итоге — единственный способ поймать перепутанные колонки.
"""

import sys
from pathlib import Path

try:
    import yaml
except ImportError:
    print("нужен PyYAML", file=sys.stderr)
    raise SystemExit(2)

ROOT = Path(__file__).resolve().parents[2]
SPEC = ROOT / "contracts" / "reports" / "digest-v1.yaml"


def ширины() -> dict:
    with SPEC.open(encoding="utf-8") as f:
        doc = yaml.safe_load(f)
    из = {f["name"]: int(f["bytes"]) for f in doc["record"]["fields"]}
    из["_total"] = int(doc["record_bytes"])
    return из


def поле(значение: str, байт: int) -> bytes:
    raw = значение.encode("utf-8")
    if len(raw) > байт:
        raise SystemExit(
            "поле не влезает: {!r} это {} байт при ширине {}".format(
                значение, len(raw), байт))
    return raw + b" " * (байт - len(raw))


def число(значение: int, байт: int) -> bytes:
    s = str(значение)
    if len(s) > байт:
        raise SystemExit("число {} не влезает в {}".format(значение, байт))
    return ("0" * (байт - len(s)) + s).encode("ascii")


# Записи. Порядок — по автору, как требует контрольный переход.
# Тело не хранится, поэтому длины заданы прямо: так видно, что итоги
# сходятся, не считая ничего в уме.
ЗАПИСИ = [
    # ник,     имя,        дата,       байт, символов
    ("alpha",  "Альфа",    "20260901",   10, 10),
    ("alpha",  "Альфа",    "20260901",   20, 20),
    ("alpha",  "Альфа",    "20260902",   30, 30),
    # Один пост — группа из одного элемента.
    ("beta",   "Бета",     "20260901",    7,  7),
    # Кириллица: байт вдвое больше символов.
    ("gamma",  "Гамма",    "20260903",  100, 50),
    ("gamma",  "Гамма",    "20260903",  200, 100),
]

# Итоги, посчитанные здесь и ожидаемые от программы:
#   alpha  3 поста,  60 байт,  60 символов
#   beta   1 пост,    7 байт,   7 символов
#   gamma  2 поста, 300 байт, 150 символов
#   ИТОГО  6 постов, 367 байт, 217 символов, 3 автора
#   байт на символ: 367 / 217 = 1.69


def main() -> int:
    if len(sys.argv) != 2:
        print("нужно: make-fixture.py <файл>", file=sys.stderr)
        return 2
    w = ширины()
    out = bytearray()
    for i, (ник, имя, дата, байт, символов) in enumerate(ЗАПИСИ):
        строка = bytearray()
        строка += поле("p-{:038d}".format(i), w["postId"])
        строка += поле(ник, w["authorNick"])
        строка += поле(имя, w["authorDisplayName"])
        строка += число(int(дата), w["createdDate"])
        строка += число(байт, w["bodyBytes"])
        строка += число(символов, w["bodyChars"])
        if len(строка) != w["_total"]:
            raise SystemExit("запись {} байт вместо {}".format(
                len(строка), w["_total"]))
        out += строка + b"\n"

    Path(sys.argv[1]).write_bytes(bytes(out))
    print("записей: {}, по {} байт".format(len(ЗАПИСИ), w["_total"]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
