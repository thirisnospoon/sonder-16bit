package sonder.shell.rest;

import org.slf4j.MDC;

import java.util.UUID;

/**
 * Идентификатор трассировки: один на запрос, от клика до строки лога ядра.
 *
 * <p>ЗАЧЕМ ОН ВООБЩЕ. Система состоит из четырёх частей, живущих в
 * разных мирах: страница в браузере, оболочка на Java, ядро на Паскале
 * под эмулятором DOS и база. Когда что-то пошло не так, вопрос звучит
 * не «какая часть сломалась», а «что случилось с ЭТИМ запросом» — и
 * ответить на него, сличая времена в трёх журналах, нельзя: команд в
 * секунду десяток, времена расходятся, а под эмулятором часы вообще
 * свои.
 *
 * <p>Идентификатор рождается ОДИН РАЗ на запрос и дальше только
 * передаётся: в MDC — чтобы попасть в каждую строку лога оболочки, в
 * заголовок ответа — чтобы его знал вызвавший, в {@code meta.traceId} —
 * чтобы его записало ядро, и в строку outbox — чтобы он остался при
 * событии навсегда.
 *
 * <p>Раньше он рождался в каждом обработчике своей строчкой
 * {@code "t-" + UUID}. Шесть таких строчек означали шесть шансов
 * разойтись — и один из них уже был реализован: обработчик, вызвавший
 * генератор дважды, выдал бы клиенту не тот идентификатор, что записал
 * в событие. Расхождение при этом выглядело бы как «в логах ничего не
 * нашлось», то есть как отсутствие следа, а не как дефект.
 */
public final class Trace {

    /** Имя в MDC. Оно же попадает в формат строки лога. */
    public static final String MDC_KEY = "trace_id";

    /** Заголовок ответа. Через него идентификатор узнаёт вызвавший. */
    public static final String HEADER = "X-Trace-Id";

    private Trace() {
    }

    /**
     * Идентификатор текущего запроса.
     *
     * <p>Вне запроса — а это фоновый дренаж outbox, опрос ноды и всё
     * прочее, что работает само, — своего запроса нет, и придумывать
     * его молча нельзя: он был бы одним на всю жизнь процесса и склеил
     * бы в поиске несвязанные вещи. Такие случаи получают собственный
     * идентификатор с явной пометкой.
     */
    public static String current() {
        String id = MDC.get(MDC_KEY);
        return id != null ? id : create("bg");
    }

    /** Новый идентификатор запроса. */
    public static String create() {
        return create("t");
    }

    private static String create(String prefix) {
        return prefix + "-" + UUID.randomUUID().toString().replace("-", "");
    }
}
