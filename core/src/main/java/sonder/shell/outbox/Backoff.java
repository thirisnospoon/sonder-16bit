package sonder.shell.outbox;

import java.time.Duration;

/**
 * Через сколько повторять неудавшуюся публикацию.
 *
 * <p>Отдельным классом, а не двумя строчками внутри дренажа, по одной
 * причине: так его можно подменить в тесте и проверить саму отсрочку, не
 * дожидаясь минут. Правило, которое нельзя завести на глазах, не
 * проверено, а понадеяно.
 *
 * <p><b>Удвоение с потолком.</b> Отказ публикации почти всегда означает,
 * что лежит то, куда публикуют, а не что событие плохое. Первый повтор
 * через секунду ловит короткий сбой; дальше растёт, чтобы не молотить по
 * лежащему соседу; потолок в пять минут — чтобы поднявшийся сосед не
 * ждал полчаса, пока до него снизойдут.
 *
 * <p>Разброса нет намеренно, и это ограничение, а не забывчивость: с
 * одним дренажёром разбрасывать нечего, а с несколькими — они пойдут на
 * упавшего соседа разом. Разброс появится тогда же, когда второй
 * дренажёр, и не раньше: сейчас он только сделал бы отсрочку
 * непроверяемой.
 */
public final class Backoff {

    /** Первая отсрочка. Короткий сбой к этому времени обычно проходит. */
    public static final Duration BASE = Duration.ofSeconds(1);

    /** Дальше не растём: поднявшийся сосед не должен ждать полчаса. */
    public static final Duration CAP = Duration.ofMinutes(5);

    private final Duration base;
    private final Duration cap;

    public Backoff() {
        this(BASE, CAP);
    }

    public Backoff(Duration base, Duration cap) {
        this.base = base;
        this.cap = cap;
    }

    /**
     * Отсрочка после {@code attempts} неудач подряд.
     *
     * <p>{@code attempts} — сколько их уже накопилось ВКЛЮЧАЯ только что
     * случившуюся. Ноль и меньше означал бы «не пытались», и отсрочки
     * тогда нет.
     */
    public Duration after(int attempts) {
        if (attempts <= 0) {
            return Duration.ZERO;
        }
        // Сдвиг, а не Math.pow: на тридцатой попытке double уже врёт, а
        // переполнение long здесь дало бы отрицательную отсрочку, то есть
        // немедленный повтор — ровно то, от чего мы уходим.
        int shift = Math.min(attempts - 1, 40);
        long millis = base.toMillis() << shift;
        if (millis <= 0 || millis > cap.toMillis()) {
            return cap;
        }
        return Duration.ofMillis(millis);
    }
}
