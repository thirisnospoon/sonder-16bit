package sonder.shell.stream;

import sonder.shell.outbox.OutboxRecord;

import java.io.IOException;

/**
 * Кому рассылать обновления ленты.
 *
 * <p><b>Зачем интерфейс.</b> Рассылка знала ровно один способ доставки —
 * SSE, — и была написана вокруг {@code SseEmitter}. Появился второй
 * носитель (шлюз IRC), и выбор был из двух: завести вторую рассылку или
 * снять с этой знание о способе доставки.
 *
 * <p>Вторая рассылка означала бы второй ответ на вопрос «чья это
 * новость». Первый даёт проекция {@code feed_entries} — та же, что
 * строит ленту; второй пришлось бы получать заново, и однажды эти два
 * ответа разошлись бы. Расхождение выглядело бы так: в браузере новость
 * есть, в IRC её нет — и наоборот.
 *
 * <p><b>Мёртвое соединение — не отказ системы,</b> а обычная жизнь
 * открытого сокета: клиент уходит не прощаясь, сеть рвётся. Поэтому
 * доставка сообщает о смерти исключением, а рассылка снимает такого
 * слушателя со списка и идёт дальше. Реализация обязана переводить свои
 * особенности в {@link IOException}: рассылка не должна знать, что у SSE
 * закрытый поток бросает {@code IllegalStateException}.
 */
public interface FeedListener {

    /**
     * Доставить событие.
     *
     * @throws IOException соединение мертво; слушателя снимут со списка
     */
    void deliver(OutboxRecord record) throws IOException;

    /**
     * Удар сердца.
     *
     * <p>Простаивающее соединение обрывают промежуточные прокси, и обрыв
     * молчаливый: клиент считает, что подписан, а событий больше не
     * будет никогда. Узнать о смерти можно только попыткой записи.
     *
     * @throws IOException соединение мертво
     */
    void beat() throws IOException;
}
