/*
  Неудачные попытки входа.

  ЗАЧЕМ ТАБЛИЦА. Контракт объявляет код LOGIN_RATE_EXCEEDED с пометкой
  `decided_by: shell`, а ARCHITECTURE.md §14 обещает ограничение частоты
  входа — и до этой миграции ни одна строка кода его не выдавала.
  Измерено: двенадцать неверных паролей подряд проходили без единого
  отказа. Подбор пароля не был ограничен ничем.

  ПОЧЕМУ РЕШАЕТ ОБОЛОЧКА, А НЕ ЯДРО. Счёт попыток требует хранилища и
  часов, а у ядра нет ни того, ни другого (ADR-0011). Это ровно тот же
  случай, что и счётчик постов за час: считает оболочка, и здесь она же
  выносит решение — правила «сколько попыток допустимо» в домене нет,
  оно операционное, как срок жизни сессии или период дренажа.

  ПИШЕТСЯ ПОПЫТКА ПО ЛЮБОМУ НИКУ, существующему или нет. Считать только
  существующие значило бы завести оракул: несуществующий ник отвечал бы
  вечно, существующий — упирался в предел, и разница выдавала бы, кто
  в системе есть.

  Ник хранится в НИЖНЕМ регистре: вход нечувствителен к регистру, и
  счёт обязан быть таким же — иначе предел обходится сменой регистра.
*/

CREATE TABLE login_attempts (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
  /* Длина как у users.nick: тот же предел контракта. */
  nick         VARCHAR(20) CHARACTER SET UTF8 NOT NULL,
  /* `attempted_at`, а не `at`: AT — зарезервированное слово Firebird, и
     колонка с таким именем роняет миграцию на разборе. Остальные
     временные колонки схемы названы так же — created_at, published_at,
     next_attempt_at. */
  attempted_at TIMESTAMP NOT NULL,
  CONSTRAINT pk_login_attempts PRIMARY KEY (id)
);

/* Счёт идёт по нику за окно, и подрезка старых — по времени.
   Один индекс обслуживает оба запроса. */
CREATE INDEX ix_login_attempts_nick_at
  ON login_attempts (nick, attempted_at);
