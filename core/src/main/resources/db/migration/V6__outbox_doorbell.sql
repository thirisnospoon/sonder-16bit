/*
  ДВЕРНОЙ ЗВОНОК ОЧЕРЕДИ.

  Триггер шлёт POST_EVENT на каждую вставку в outbox. Потребитель, если
  он есть и подписан, просыпается сразу вместо того, чтобы ждать
  следующего опроса.

  ЭТО НЕ ЗАМЕНА ОПРОСУ, А ДОБАВКА К НЕМУ. Событие Firebird недолговечно
  и полезной нагрузки не несёт: пропущенное уведомление означало бы
  навсегда застрявшую строку, если бы других способов её найти не было.
  Источник правды — таблица, и опрос остаётся основным путём; звонок
  только укорачивает ожидание с секунды до миллисекунд.

  POST_EVENT СРАБАТЫВАЕТ ПРИ КОММИТЕ, а не в момент вызова. Это ровно то
  поведение, которое здесь нужно: потребитель, разбуженный раньше
  коммита, не увидел бы строки и ушёл бы ни с чем. Так устроен Firebird,
  и на это здесь рассчитывают.

  ИМЯ СОБЫТИЯ ЗАШИТО В ТРИГГЕР И В КОД. Разойтись они могут молча:
  слушатель подпишется на то, чего никто не шлёт, и будет просто спать —
  а выглядеть это будет как «звонок не работает». Поэтому имя одно, и
  проверка на него есть.
*/

SET TERM ^ ;

CREATE TRIGGER outbox_doorbell FOR outbox
ACTIVE AFTER INSERT POSITION 0
AS
BEGIN
  POST_EVENT 'sonder_outbox';
END^

SET TERM ; ^
