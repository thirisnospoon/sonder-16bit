/*
  ПРОЕКЦИЯ ЛЕНТЫ.

  Первая read-модель. Выводится из событий очереди и потому переживает
  пересборку: потеряй эту таблицу целиком — её можно построить заново,
  прогнав очередь с начала. Таблицы агрегатов такого не умеют, и именно
  поэтому проекции живут отдельной миграцией, а не в V1.

  ФАНАУТ НА ЗАПИСЬ. На каждое post.created кладётся по строке в ленту
  каждого подписчика автора и самого автора. Обратный подход — собирать
  ленту на чтение соединением с подписками — дешевле пишет и дороже
  читает, а читают ленту на порядок чаще, чем пишут посты.

  ПЕРВИЧНЫЙ КЛЮЧ ДАЁТ ИДЕМПОТЕНТНОСТЬ. Обработчик очереди обязан быть
  идемпотентным: между обработкой и коммитом система может упасть, и
  событие приедет второй раз. Пара (владелец, пост) уникальна, и
  повторная вставка через UPDATE OR INSERT ничего не портит.

  ВРЕМЯ ПОСТА, А НЕ ВСТАВКИ. Лента упорядочена по created_at, и это
  время создания поста. Возьми время вставки — и пост, доехавший до
  ленты с задержкой из-за повтора, встал бы не на своё место.

  ВНЕШНИЕ КЛЮЧИ ЕСТЬ, хотя это и проекция. Строка на несуществующий пост
  — дефект фанаута, и ловить его лучше базе, чем читателю ленты. Удаление
  поста при этом мягкое (status = DELETED), так что ключ никому не мешает.
*/

CREATE TABLE feed_entries (
  /* Чья лента. */
  owner_id    VARCHAR(40) CHARACTER SET UTF8 NOT NULL,
  post_id     VARCHAR(40) CHARACTER SET UTF8 NOT NULL,
  /* Автор поста. По нему снимаются строки при отписке — иначе пришлось
     бы соединяться с posts на каждое follow.removed. */
  author_id   VARCHAR(40) CHARACTER SET UTF8 NOT NULL,
  /* Время создания поста, не вставки строки. */
  created_at  TIMESTAMP   NOT NULL,
  CONSTRAINT pk_feed_entries PRIMARY KEY (owner_id, post_id),
  CONSTRAINT fk_feed_owner FOREIGN KEY (owner_id) REFERENCES users (id),
  CONSTRAINT fk_feed_post FOREIGN KEY (post_id) REFERENCES posts (id),
  CONSTRAINT fk_feed_author FOREIGN KEY (author_id) REFERENCES users (id)
);

/* Страница ленты: владелец равенством, дальше убывание по времени и по
   идентификатору. Идентификатор в ключе не для порядка ради порядка, а
   чтобы два поста одной секунды имели устойчивое взаимное положение:
   без этого курсор мог бы пропустить строку или выдать её дважды. */
CREATE DESCENDING INDEX ix_feed_page ON feed_entries (owner_id, created_at, post_id);

/* Отписка снимает строки по паре (владелец, автор). */
CREATE INDEX ix_feed_author ON feed_entries (owner_id, author_id);
