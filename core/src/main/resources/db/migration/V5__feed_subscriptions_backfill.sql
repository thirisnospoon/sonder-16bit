/*
  Разовая переливка того, что уже есть в follows.

  Не «на всякий случай»: без неё все существующие подписки перестали бы
  работать в тот момент, когда фанаут переключится на новую таблицу, и
  выглядело бы это как «ленты вдруг опустели». Читается follows здесь
  один раз, миграцией, а не кодом events в рантайме — граница ADR-0016
  проходит по чтениям кода, а не по разовому переносу данных.
*/
INSERT INTO feed_subscriptions (follower_id, target_id, seen_at)
  SELECT f.follower_id, f.target_id, f.created_at FROM follows f;
