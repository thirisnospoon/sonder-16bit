/*
  Отпечаток токена вместо самого токена.

  ЗАЧЕМ. Токен лежал в базе как есть и служил первичным ключом: утечка
  дампа означала угон ВСЕХ живых сессий, без подбора и без следов.
  Записано это было в docs/THREAT-MODEL.md как самый дорогой из
  незакрытых долгов; здесь он закрывается.

  ПОЧЕМУ SHA-256, А НЕ BCRYPT. Пароль человек выбирает сам, и он
  угадываем — оттого bcrypt со стоимостью 12, то есть нарочито
  медленный. Токен выдаёт SecureRandom, в нём 256 бит энтропии, и
  подбирать его перебором некому: быстрый хэш здесь достаточен, а
  медленный стоил бы сотни миллисекунд НА КАЖДЫЙ запрос, потому что
  сессия проверяется всегда.

  ИМЯ КОЛОНКИ МЕНЯЕТСЯ ВМЕСТЕ СО СМЫСЛОМ. Колонка `token`, хранящая
  отпечаток, приглашает сравнить её с кукой напрямую — и такое сравнение
  молча вернуло бы «сессии нет» для каждого. Имя `token_hash` этого не
  позволяет.

  ЖИВЫЕ СЕССИИ СБРАСЫВАЮТСЯ. Пересчитать отпечатки из старых значений
  можно было бы средствами Firebird, но это означало бы протащить
  открытые токены ещё через один код. Всем придётся войти заново — цена
  однократная и понятная, а именно так и полагается поступать при смене
  способа хранения секрета.
*/

/*
  ТАБЛИЦА ПЕРЕСОЗДАЁТСЯ, а не переименовывается колонка.

  `ALTER TABLE sessions ALTER COLUMN token TO token_hash` Firebird
  отвергает: «Cannot update index segment used by an Integrity
  Constraint» — колонка входит в первичный ключ, и переименовать её,
  не разобрав ключ, нельзя. Разбирать и собирать ключ ради имени
  колонки — три операции там, где хватает одной: строки всё равно
  удаляются целиком.
*/

DROP TABLE sessions;

CREATE TABLE sessions (
  /* Шестьдесят четыре знака — ровно длина SHA-256 в шестнадцатеричной
     записи. Ширина колонки та же, что была у токена: 43 знака base64url
     помещались с запасом, отпечаток заполняет её ровно. */
  token_hash  VARCHAR(64) CHARACTER SET ASCII NOT NULL,
  user_id     VARCHAR(40) CHARACTER SET UTF8  NOT NULL,
  created_at  TIMESTAMP   NOT NULL,
  expires_at  TIMESTAMP   NOT NULL,
  /* Сессию никто не правит параллельно, и версия ей не нужна. Она здесь
     ради того, чтобы правило «у каждого агрегата есть версия» осталось
     сплошным. */
  version     INTEGER     DEFAULT 0 NOT NULL,
  CONSTRAINT pk_sessions PRIMARY KEY (token_hash),
  CONSTRAINT fk_sessions_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE INDEX ix_sessions_user ON sessions (user_id);
