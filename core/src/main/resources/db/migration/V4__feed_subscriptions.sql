/*
  КОПИЯ ГРАФА ПОДПИСОК, КОТОРУЮ ВЕДЁТ `events`.

  Рядом уже есть таблица follows, и это не дублирование по недосмотру.
  follows принадлежит `core`: её пишет ход команды вместе с решением ядра.
  Эта — принадлежит `events` и строится из событий follow.created и
  follow.removed, которые и так проходят через дренаж.

  ЗАЧЕМ. `events` обязан строить проекции только на том, чем владеет сам
  (ADR-0016). Фанаут поста по подписчикам — самая частая операция
  конвейера, и спрашивать множество подписок у `core` пришлось бы на
  КАЖДЫЙ пост: список неограниченной длины по IIOP упёрся бы ровно в
  измеренный потолок дренажа (S5, около пятисот событий в секунду).
  Собственная таблица снимает вопрос: фанаут остаётся одним множественным
  INSERT.

  ЧЕМ ПЛАТИМ. Копия отстаёт от оригинала ровно настолько, насколько
  отстаёт дренаж, — тем же отставанием, с которым и так живёт лента.
  Подписки, заведённые ДО этой миграции, переливаются один раз следующей
  миграцией: честнее разовый перенос, чем надежда на то, что очередь
  хранится вечно и её можно проиграть с начала.

  ВНЕШНИЕ КЛЮЧИ ЕСТЬ. База одна, и ссылочная целостность здесь ловит
  дефект фанаута дешевле, чем читатель ленты. Разделение по ADR-0016
  проходит по границе ЧТЕНИЙ в коде, а не по границе схемы.

  ПЕРЕЛИВКА СУЩЕСТВУЮЩИХ ПОДПИСОК — В СЛЕДУЮЩЕЙ МИГРАЦИИ, и не ради
  порядка. Firebird не видит только что созданную таблицу в той же
  транзакции, а Flyway выполняет скрипт целиком одной транзакцией: INSERT
  сюда же падает с «Table unknown». Выяснено прогоном.
*/

CREATE TABLE feed_subscriptions (
  follower_id VARCHAR(40) CHARACTER SET UTF8 NOT NULL,
  target_id   VARCHAR(40) CHARACTER SET UTF8 NOT NULL,
  /* Когда подписка попала в проекцию, а не когда заведена: первое
     принадлежит events, второе — core, и путать их не надо. */
  seen_at     TIMESTAMP   NOT NULL,
  CONSTRAINT pk_feed_subscriptions PRIMARY KEY (follower_id, target_id),
  CONSTRAINT fk_feed_subs_follower FOREIGN KEY (follower_id) REFERENCES users (id),
  CONSTRAINT fk_feed_subs_target FOREIGN KEY (target_id) REFERENCES users (id)
);

/* Фанаут идёт от автора к подписчикам: это направление и нужно индексу. */
CREATE INDEX ix_feed_subs_target ON feed_subscriptions (target_id);
