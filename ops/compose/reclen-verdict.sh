#!/usr/bin/env bash
# Вердикт о длине записей: общий для обеих дорог к своду.
#
#   reclen-verdict <файл> <контракт> <команда интерпретатора...>
#
# ЗАЧЕМ ОТДЕЛЬНЫМ ФАЙЛОМ. Проверку длины проходят две выгрузки: ручная
# (`./sonder report`, интерпретатор в своём контейнере) и ночная (служба
# расписания, интерпретатор внутри её же образа). Дороги разные, а
# вопрос один, и ответ на него обязан быть один.
#
# Написать вердикт дважды означало бы завести две проверки, которые
# однажды разойдутся — и разойдутся молча, потому что расходятся они
# только на испорченных данных, то есть в тот единственный раз, когда
# нужны. Здесь ровно один экземпляр: `ops/ci/reclen.sh` зовёт его с
# хоста, образ бегунка несёт его внутри.
#
# ЧТО ИМЕННО СВЕРЯЕТСЯ. Три независимых ответа на три разных вопроса:
#
#   сколько записей ДОЛЖНО быть   — по размеру файла в байтах;
#   стоит ли перевод строки ТАМ,
#     где ему положено             — по счёту байтов в Brainfuck;
#   нет ли переводов строки ЕЩЁ
#     где-нибудь                   — по общему числу байтов 0x0A.
#
# Совпадение всех трёх и есть проверка; каждый по отдельности слеп.
# Размер файла ничего не знает о переводах строк: файл, где одна запись
# на байт короче, а другая на байт длиннее, его проходит. Программа на
# Brainfuck не знает размера файла и не смотрит значения байтов внутри
# записи — она считает ПОЛОЖЕНИЯ. А счёт всех 0x0A закрывает последнюю
# щель: перевод строки ВНУТРИ записи не сдвигает ничего и потому не
# виден ни по размеру, ни по положению — но он лишний, и его видно по
# числу.
#
# Третий счёт стоит здесь, а не в Brainfuck, по замеру: проверка
# значения каждого байта обходилась в 33 секунды живого времени на
# выгрузке из 5061 записи, потому что всякая работа с байтом в том языке
# стоит столько шагов, каково его значение. `tr` считает то же самое за
# миллисекунды и тоже в байтах — `wc -c`, а не `wc -m`.
set -uo pipefail

FILE="${1:?нужен путь к файлу выгрузки}"
CONTRACT="${2:?нужен путь к контракту свода}"
shift 2
[ "$#" -gt 0 ] || { echo "нужна команда интерпретатора" >&2; exit 2; }

fail() { echo "ПРОВАЛ: $*" >&2; exit 1; }

[ -f "$FILE" ] || fail "нет файла $FILE"
[ -f "$CONTRACT" ] || fail "нет контракта $CONTRACT"

# Длину диктует контракт, и разбирается он ровно здесь. Второй экземпляр
# этой строки на другой дороге означал бы, что контракт правит одну
# сторону из двух.
LEN="$(awk '/^record_bytes:/ { print $2 }' "$CONTRACT")"
[ -n "$LEN" ] && [ "$LEN" -gt 0 ] 2>/dev/null \
  || fail "в контракте $CONTRACT не нашлось record_bytes"

BYTES="$(wc -c < "$FILE")"
STRIDE=$((LEN + 1))
if [ "$((BYTES % STRIDE))" -ne 0 ]; then
  fail "размер файла $BYTES не делится на $STRIDE: файл оборван или разметка не та"
fi
EXPECTED=$((BYTES / STRIDE))

# Запись из одних нулей — признак конца. Ноль не встречается в настоящей
# записи: она состоит из текста, цифр и пробелов. Дописывается здесь, а
# не выгрузкой: файл для COBOL обязан остаться таким, каким его читает
# COBOL.
MARKS="$( { cat "$FILE"; head -c "$LEN" /dev/zero; printf '\n'; } | "$@" )" \
  || fail "интерпретатор не отработал"

GOOD="$(printf '%s' "$MARKS" | tr -cd '.' | wc -c)"
BAD="$(printf '%s' "$MARKS" | tr -cd '!' | wc -c)"

if [ "$BAD" -gt 0 ]; then
  # Значим ПЕРВЫЙ восклицательный знак: после записи неверной длины
  # выравнивание потеряно, и следующие отметки говорят лишь о том, что
  # поток разошёлся с разметкой.
  WHERE="$(printf '%s' "$MARKS" | awk '{ print index($0, "!") }')"
  echo "записей не той длины; первая — номер $WHERE из $EXPECTED" >&2
  echo "ожидалось $LEN байт на запись и перевод строки" >&2
  echo "после сбоя выравнивание потеряно, дальнейшие отметки не значимы" >&2
  LC_ALL=C awk -v n="$WHERE" \
    'NR >= n && NR <= n + 2 { print "  запись " NR ": " length($0) " байт" }' \
    "$FILE" >&2
  exit 1
fi

# Отметок меньше, чем записей, — тоже провал: программа остановилась
# раньше, чем кончился файл. Так выглядит оборванный вход.
if [ "$GOOD" -ne "$EXPECTED" ]; then
  fail "отметок $GOOD, а записей $EXPECTED: проверка не дошла до конца файла"
fi

# Лишний перевод строки ВНУТРИ записи не сдвигает ничего: длина та же,
# положения те же. Виден он только по общему счёту. `LC_ALL=C` тут
# обязателен по той же причине, по которой затевалось второе мнение:
# многобайтовая локаль превращает счёт байтов в счёт символов.
NEWLINES="$(LC_ALL=C tr -cd '\n' < "$FILE" | wc -c)"
if [ "$NEWLINES" -ne "$EXPECTED" ]; then
  fail "переводов строки $NEWLINES, а записей $EXPECTED: лишние стоят внутри записей"
fi

echo "  длина записей: $EXPECTED по $LEN байт, сверено на Brainfuck"
