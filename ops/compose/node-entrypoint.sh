#!/usr/bin/env bash
# Подъём NODE-7.
#
# ПОРЯДОК ОБЯЗАТЕЛЕН, и compose его не обеспечивает. Нульмодем DOSBox —
# КЛИЕНТ: он идёт на порт оболочки, и если порт ещё не слушает, эмулятор
# не дождётся и не повторит. `depends_on` говорит лишь о том, что
# контейнер запущен, а не о том, что порт занят.
#
# Поэтому ждём порт здесь, своими руками, и говорим об этом вслух: молча
# поднявшаяся нода, которая ни к чему не подключилась, выглядит точно так
# же, как работающая.
#
# ИМЕНА ПЕРЕМЕННЫХ ЛАТИНИЦЕЙ. Это ограничение самой оболочки: кириллица в
# идентификаторе не ошибка присваивания, а «command not found» — строка
# перестаёт быть присваиванием и становится вызовом команды. Скрипт при
# этом продолжает работать, ожидание порта молча превращается в ноль
# попыток, и эмулятор поднимается в пустоту.
set -uo pipefail

HOST="${SONDER_LINE_HOST:-app}"
PORT="${SONDER_LINE_PORT:-5077}"
WAIT="${SONDER_LINE_WAIT:-120}"

echo "NODE-7: ждём линию на $HOST:$PORT"

ready=0
for _ in $(seq 1 "$WAIT"); do
  if (exec 3<>"/dev/tcp/$HOST/$PORT") 2>/dev/null; then
    exec 3<&- 2>/dev/null
    exec 3>&- 2>/dev/null
    ready=1
    break
  fi
  sleep 1
done

if [ "$ready" -ne 1 ]; then
  echo "NODE-7: линия не открылась за $WAIT с — подключаться некуда" >&2
  exit 1
fi

echo "NODE-7: линия слушает, поднимаем эмулятор"

# ЖУРНАЛ ЯДРА НАРУЖУ.
#
# NODE7.LOG пишется программой внутрь смонтированного диска C:, то есть
# в /node — и там же и остаётся. Снаружи ядро при этом немо: `docker
# compose logs node` показывает только строки этого скрипта, а всё, что
# сказала сама нода — сквозной след команды в том числе, — надо идти
# доставать `exec`-ом. След, за которым надо ходить, следом не является.
#
# `-F`, а не `-f`: программа под DOSBox открывает файл заново, и `-f`
# остался бы смотреть на прежний дескриптор.
#
# `-n 0` — только новое. Журнал переживает перезапуск контейнера
# намеренно (склеенная история ценнее экономии), но перечитывать его с
# начала при каждом перезапуске значит выдавать вчерашние строки за
# сегодняшние. Успеть tail успевает: он поднимается раньше эмулятора, а
# первую строку нода пишет уже после загрузки DOS.
touch /node/NODE7.LOG
tail -F -n 0 /node/NODE7.LOG 2>/dev/null | sed -u "s/^/NODE-7| /" &

# Адрес подставляется в конфигурацию здесь: DOSBox не умеет переменных
# окружения, а держать в образе жёстко прописанный хост значит запретить
# запускать его где-либо ещё.
sed -e "s/@HOST@/$HOST/" -e "s/@PORT@/$PORT/" \
    /node/dosbox.conf > /tmp/dosbox.conf

exec dosbox -conf /tmp/dosbox.conf -exit
