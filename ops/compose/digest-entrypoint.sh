#!/usr/bin/env bash
# Расписание ночного свода.
#
# ЗАЧЕМ ЭТОТ ФАЙЛ ВООБЩЕ ПОЯВИЛСЯ. Свод назывался ночным, а запускался
# тем, что человек набирал `./sonder report`. «Ночной» было названием, а
# не свойством — тот же класс утверждения без силы, что и порождённый
# писатель, которым ничего не пользовалось.
#
# ВРЕМЯ ТОЛЬКО UTC, И ЭТО РЕШЕНИЕ, А НЕ УПРОЩЕНИЕ. В местном времени
# сутки дважды в год длятся не 86400 секунд: при переходе на летнее
# время 03:00 может не наступить вовсе, при обратном — наступить дважды.
# Расписание, считающее «плюс сутки», в первом случае пропускает свод, во
# втором считает его дважды. Второй свод за те же сутки — не ошибка
# выполнения, а два разных отчёта с одинаковым заголовком.
#
# ЗАПУСК СТРОГО ПОСЛЕ УКАЗАННОГО МОМЕНТА. Если контейнер поднялся ровно в
# назначенную секунду, ждать он будет сутки, а не ноль. Иначе цикл при
# нулевом ожидании крутился бы вхолостую до конца минуты, запуская свод
# столько раз, сколько успеет.
set -uo pipefail

DAY_SECONDS=86400

# Проверка формата отдельно от разбора. `date` понимает и «25:00», и
# «3»,  и «завтра» — расписание с опечаткой означало бы не то, что
# написано, и молча.
проверить_время() {
  case "$1" in
    [01][0-9]:[0-5][0-9] | 2[0-3]:[0-5][0-9]) return 0 ;;
    *) return 1 ;;
  esac
}

# Сколько секунд ждать до следующего наступления ЧЧ:ММ по UTC.
# Второй аргумент — «сейчас» в секундах эпохи; он есть ради проверки:
# расписание, которое нельзя спросить о будущем, проверяется только
# ожиданием суток.
сколько_ждать() {
  local at="$1" now="$2" day target
  проверить_время "$at" || {
    echo "время «$at» не в виде ЧЧ:ММ" >&2
    return 1
  }
  day="$(date -u -d "@$now" +%Y-%m-%d)" || return 1
  target="$(date -u -d "$day $at UTC" +%s)" || return 1
  if [ "$target" -le "$now" ]; then
    target=$((target + DAY_SECONDS))
  fi
  echo $((target - now))
}

# Один прогон свода: выгрузка и пакет. Оба шага здесь, в одном образе, и
# это осознанно — см. пояснение в Dockerfile о сокете Docker.
прогон() {
  local out="${SONDER_REPORT_DIR:-/data}"
  mkdir -p "$out"
  echo "$(date -u +%FT%TZ) свод: выгрузка"
  java -cp /app/sonder.jar \
       -Dloader.main=sonder.report.DigestExport \
       org.springframework.boot.loader.PropertiesLauncher \
       "$out/posts.dat" || return 1
  echo "$(date -u +%FT%TZ) свод: пакет"
  SONDER_DIGEST_INPUT="$out/posts.dat" \
  SONDER_DIGEST_OUTPUT="$out/digest.txt" \
    /usr/local/bin/digest || return 1
  echo "$(date -u +%FT%TZ) свод: готово"
}

# Точка входа умеет отвечать на вопрос, а не только работать: без этого
# расписание проверялось бы ожиданием суток.
if [ "${1:-}" = "next-in" ]; then
  сколько_ждать "${2:?нужно время в виде ЧЧ:ММ}" "${3:-$(date -u +%s)}"
  exit $?
fi

if [ "${1:-}" = "once" ]; then
  прогон
  exit $?
fi

AT="${SONDER_DIGEST_AT:-03:00}"

if ! проверить_время "$AT"; then
  echo "расписание «$AT» не в виде ЧЧ:ММ — свод не запущен" >&2
  exit 1
fi

# ПРОВЕРОЧНОГО РЕЖИМА ЗДЕСЬ НЕТ, и это осознанно. Соблазн завести
# «каждые N секунд» ради проверки велик, но тогда проверялась бы ветка,
# которой ночью не существует, а настоящая — та, что считает до часа —
# оставалась бы непройденной. Расписание проверяется тем, что срок
# ставят на минуту вперёд: путь исполняется ровно тот же.
echo "свод: ежедневно в $AT UTC"

while true; do
  WAIT="$(сколько_ждать "$AT" "$(date -u +%s)")" || exit 1
  echo "$(date -u +%FT%TZ) свод: ждать $WAIT с"
  sleep "$WAIT"
  # ОТКАЗ ПРОГОНА НЕ ОСТАНАВЛИВАЕТ РАСПИСАНИЕ. База может быть недоступна
  # в эту минуту и доступна в следующую; служба, умирающая от одной
  # неудачной ночи, тихо перестаёт считать свод вовсе.
  прогон || echo "$(date -u +%FT%TZ) свод: прогон отказал" >&2
done
