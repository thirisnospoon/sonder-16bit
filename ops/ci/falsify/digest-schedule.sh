#!/usr/bin/env bash
# Ловит ли проверка расписания то, что ломается на самом деле.
#
# Два дефекта, и оба тихие.
#
#   1. МЕСТНОЕ ВРЕМЯ ВМЕСТО UTC. Снимается один флаг `-u`, и расчёт
#      начинает считать сутки по часовому поясу машины. В большинстве
#      прогонов ничего не меняется: разница видна только в ночь перевода
#      стрелок, то есть дважды в год. Проверка обязана краснеть КАЖДЫЙ
#      раз — иначе она поймает дефект в последнее воскресенье марта.
#
#   2. «РОВНО В СРОК» КАК НОЛЬ ОЖИДАНИЯ. Строгое сравнение заменяется
#      нестрогим, и контейнер, поднявшийся ровно в назначенную секунду,
#      получает ноль. Цикл со сном в ноль секунд крутит свод столько
#      раз, сколько успеет до конца минуты — база при этом жива, отчёты
#      пишутся, и всё выглядит работающим.
set -uo pipefail

ROOT="$(cd "$(dirname "$0")/../../.." && pwd)"
ENTRY="$ROOT/ops/compose/digest-entrypoint.sh"
BACKUP="$(mktemp)"

cd "$ROOT" || exit 1

cp "$ENTRY" "$BACKUP"
trap 'cp "$BACKUP" "$ENTRY"; rm -f "$BACKUP"' EXIT

bash ops/ci/digest-schedule-test.sh > /tmp/f-sched-0.log 2>&1 \
  || { echo "  БАЗА КРАСНАЯ"; exit 1; }

# --- 1. Местное время вместо UTC --------------------------------------
sed -i 's|target="$(date -u -d "$day $at UTC" +%s)"|target="$(date -d "$day $at" +%s)"|' \
  "$ENTRY"
if ! grep -q 'date -d "\$day \$at" +%s' "$ENTRY"; then
  echo "  ДЕФЕКТ НЕ ВНЕСЁН: строка расчёта изменилась, правь фальсификацию"
  exit 1
fi
bash ops/ci/digest-schedule-test.sh > /tmp/f-sched-1.log 2>&1 \
  && { echo "  ЗЕЛЕНО ПРИ РАСЧЁТЕ В МЕСТНОМ ВРЕМЕНИ"; exit 1; }

cp "$BACKUP" "$ENTRY"

# --- 2. Ноль ожидания при совпадении с точностью до секунды -----------
sed -i 's|if \[ "$target" -le "$now" \]; then|if [ "$target" -lt "$now" ]; then|' \
  "$ENTRY"
if ! grep -q '"\$target" -lt "\$now"' "$ENTRY"; then
  echo "  ДЕФЕКТ НЕ ВНЕСЁН: строка сравнения изменилась, правь фальсификацию"
  exit 1
fi
bash ops/ci/digest-schedule-test.sh > /tmp/f-sched-2.log 2>&1 \
  && { echo "  ЗЕЛЕНО ПРИ НУЛЕВОМ ОЖИДАНИИ В СРОК"; exit 1; }

echo "  местное время и нулевое ожидание ловятся"
