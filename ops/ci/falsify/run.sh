#!/usr/bin/env bash
# Проверка проверок: умеют ли они падать.
#
# ЗАЧЕМ ЭТО ОТДЕЛЬНОЙ ЦЕЛЬЮ. Дисциплина проекта требует, чтобы у каждой
# проверки была способность упасть, и до сих пор это подтверждалось
# разово, вручную, скриптами из временного каталога — то есть терялось
# сразу после подтверждения. Риск R11 в RISKS.md говорит, что «быть
# внимательнее» механикой не является; это она и есть.
#
# КАЖДАЯ ФАЛЬСИФИКАЦИЯ ВНОСИТ НАСТОЯЩИЙ ДЕФЕКТ и требует, чтобы
# проверка покраснела ИМЕННО НА НЁМ. Восстановление — через trap, чтобы
# прерванный прогон не оставил дерево испорченным.
#
# ЗДЕСЬ НЕ ВСЕ ПРОВЕРКИ, И ЭТО НАПИСАНО ПРЯМО. Часть фальсификаций
# требует пересборки образов или поднятого состава и идёт минутами;
# сводить их в одну цель значило бы получить цель, которую никто не
# запускает. Список ниже перечисляет ВСЕ проверки — и те, чья
# фальсификация здесь, и те, чья лежит рядом с ними самими.
set -uo pipefail

ROOT="$(cd "$(dirname "$0")/../../.." && pwd)"
HERE="$(cd "$(dirname "$0")" && pwd)"

cd "$ROOT" || exit 1

rc=0

# Имена латиницей: кириллица в идентификаторе bash — не присваивание,
# а «command not found», и скрипт продолжает с пустой переменной. Эта
# функция была написана с `$имя` и `$файл` и объявила несуществующими
# все три фальсификации сразу.
run_one() {
  local title="$1" file="$2"
  echo
  echo "==> $title"
  if bash "$HERE/$file"; then
    echo "  умеет падать"
  else
    echo "  НЕ УМЕЕТ ПАДАТЬ ЛИБО СЛОМАНА" >&2
    rc=1
  fi
}

run_one "переводы строк"            eol.sh
run_one "идентификаторы в bash"     shell.sh
run_one "бюджеты TURBOCORE §12"     budgets.sh
run_one "граф модулей Pascal"       layers.sh

cat <<'ТЕКСТ'

==> фальсификации, живущие отдельно

Требуют пересборки образов или поднятого состава и потому не входят
сюда. Каждая проверена вручную и описана рядом со своей проверкой:

  дрейф контрактов        изменением контракта без перегенерации
  самопроверка валидатора 17 намеренных дефектов, ./sonder contracts-selftest
  слои Java (ArchUnit)    намеренными нарушителями в тестах
  размер бинарника        заниженным пределом NODE7_MAX_BYTES
  Lighthouse              порогом 101 и отчётом непрошедшего прогона
  сквозной след           ядром, переставшим писать trace в журнал
  отказ и возвращение     заниженным сроком возвращения
  лаг read-model          заниженной целью SLO и порогом звонка
                          (ops/ci/falsify/lag.sh, нужен поднятый состав)
  время ответа входа      снятым фиктивным хэшем: 272 мс против 40
  доступ по контракту     лентой, объявленной открытой
  конверт отказа          отключённым исключением на отсутствие маршрута
  предел входа            снятой проверкой предела
  отпечаток токена        возвратом токена в базу открытым текстом
  поток обновлений        состоянием закрытия, не совпадающим никогда

ТЕКСТ

if [ "$rc" -ne 0 ]; then
  echo "ЕСТЬ ПРОВЕРКИ, КОТОРЫЕ НЕ УМЕЮТ ПАДАТЬ" >&2
else
  echo "все фальсификации сработали"
fi
exit "$rc"
