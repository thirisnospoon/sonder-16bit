#!/usr/bin/env bash
# Проверка проверок: умеют ли они падать.
#
#   bash ops/ci/falsify/run.sh          быстрые: секунды, ничего не нужно
#   bash ops/ci/falsify/run.sh --slow   плюс те, что требуют образа или
#                                       поднятого состава
#
# ЗАЧЕМ ЭТО ОТДЕЛЬНОЙ ЦЕЛЬЮ. Дисциплина проекта требует, чтобы у каждой
# проверки была способность упасть, и до сих пор это подтверждалось
# разово, вручную, скриптами из временного каталога — то есть терялось
# сразу после подтверждения. Риск R11 в RISKS.md говорит, что «быть
# внимательнее» механикой не является; это она и есть.
#
# КАЖДАЯ ФАЛЬСИФИКАЦИЯ ВНОСИТ НАСТОЯЩИЙ ДЕФЕКТ и требует, чтобы
# проверка покраснела ИМЕННО НА НЁМ. Восстановление — через trap, чтобы
# прерванный прогон не оставил дерево испорченным.
#
# ФАЛЬСИФИКАЦИЯ ТОЖЕ ГНИЁТ, И ЭТО ИЗМЕРЕНО, А НЕ ПРЕДПОЛОЖЕНО. Проверка
# достижимости модулей стерегла две стороны, и вторую фальсификация
# трогала добавлением TcLog в uses ноды. В день, когда журнал ядра
# подключили к линии, TcLog вошёл в программу и ушёл из списка
# недостижимых: фальсификация стала добавлять уже добавленное и тихо
# зеленеть. Обнаружилось это спустя несколько срезов и только потому,
# что прогон случился вообще.
#
# Отсюда СПИСКИ НИЖЕ И СВЕРКА С КАТАЛОГОМ: скрипт-фальсификация, которую
# не зовёт никто, — не запас на будущее, а обещание без силы. Такие
# лежали здесь двумя штуками.
set -uo pipefail

ROOT="$(cd "$(dirname "$0")/../../.." && pwd)"
HERE="$(cd "$(dirname "$0")" && pwd)"

cd "$ROOT" || exit 1

SLOW=0
case "${1:-}" in
  "")        ;;
  --slow)    SLOW=1 ;;
  *)         echo "неизвестный ключ «$1»; есть только --slow" >&2; exit 2 ;;
esac

rc=0

# Имена латиницей: кириллица в идентификаторе bash — не присваивание,
# а «command not found», и скрипт продолжает с пустой переменной. Эта
# функция была написана с `$имя` и `$файл` и объявила несуществующими
# все три фальсификации сразу.
run_one() {
  local title="$1" file="$2"
  echo
  echo "==> $title"
  if bash "$HERE/$file"; then
    echo "  умеет падать"
  else
    echo "  НЕ УМЕЕТ ПАДАТЬ ЛИБО СЛОМАНА" >&2
    rc=1
  fi
}

# Пара «файл|название». Быстрые не требуют ни образов, ни состава и
# идут секунды; медленные пересобирают образ или ходят в поднятую
# систему, и потому включаются ключом, а не всегда.
FAST=(
  "eol.sh|переводы строк"
  "shell.sh|идентификаторы в bash"
  "language.sh|language ratchet"
  "budgets.sh|бюджеты TURBOCORE §12"
  "layers.sh|граф модулей Pascal"
  "restart.sh|политика перезапуска"
  "digest-schedule.sh|расписание свода"
)

SLOW_ONES=(
  "report.sh|свод на COBOL — нужен образ пакета"
  "lag.sh|лаг read-model — нужен поднятый состав"
  "domain-crosscheck.sh|второе мнение о домене — нужен образ Пролога"
)

# --- Ни одна фальсификация не осталась без запуска ---------------------
#
# Списки выше — не оглавление, а единственный способ быть запущенным.
# Файл, забытый в обоих, лежал бы тут годами, выглядя охраной.
echo "==> сверка списков с каталогом"
MISSING=0
for path in "$HERE"/*.sh; do
  name="$(basename "$path")"
  [ "$name" = "run.sh" ] && continue
  if ! printf '%s\n' "${FAST[@]}" "${SLOW_ONES[@]}" | grep -q "^$name|"; then
    echo "  $name не назван ни в одном списке — его не зовёт никто" >&2
    MISSING=1
  fi
done
for entry in "${FAST[@]}" "${SLOW_ONES[@]}"; do
  name="${entry%%|*}"
  if [ ! -f "$HERE/$name" ]; then
    echo "  $name назван в списке, но такого файла нет" >&2
    MISSING=1
  fi
done
if [ "$MISSING" -ne 0 ]; then
  rc=1
else
  echo "  все ${#FAST[@]} быстрых и ${#SLOW_ONES[@]} медленных на месте"
fi

for entry in "${FAST[@]}"; do
  run_one "${entry#*|}" "${entry%%|*}"
done

if [ "$SLOW" -eq 1 ]; then
  for entry in "${SLOW_ONES[@]}"; do
    run_one "${entry#*|}" "${entry%%|*}"
  done
else
  echo
  echo "==> медленные пропущены (ключ --slow их включает)"
  for entry in "${SLOW_ONES[@]}"; do
    echo "  ${entry#*|}"
  done
fi

cat <<'ТЕКСТ'

==> фальсификации без своего скрипта

Живут рядом со своими проверками: внести дефект там значит поменять
контракт, порог или образ, и отдельным файлом это не выражается. Каждая
проверена вручную и описана рядом с проверкой.

  дрейф контрактов        изменением контракта без перегенерации
  самопроверка валидатора 17 намеренных дефектов, ./sonder contracts-selftest
  корпус решений домена   порождается настоящим ядром; расхождение с ним
                          ловит второе мнение (см. медленные выше)
  сборщик Brainfuck       6 намеренных дефектов, ./sonder reclen-test
  слои Java (ArchUnit)    намеренными нарушителями в тестах
  размер бинарника        заниженным пределом NODE7_MAX_BYTES
  Lighthouse              порогом 101 и отчётом непрошедшего прогона
  сквозной след           ядром, переставшим писать trace в журнал
  отказ и возвращение     заниженным сроком возвращения
  время ответа входа      снятым фиктивным хэшем: 272 мс против 40
  доступ по контракту     лентой, объявленной открытой
  конверт отказа          отключённым исключением на отсутствие маршрута
  предел входа            снятой проверкой предела
  отпечаток токена        возвратом токена в базу открытым текстом
  поток обновлений        состоянием закрытия, не совпадающим никогда
  длина записей свода     перекосом на байт при верном размере файла,
                          обрывом, лишним переводом строки внутри записи
                          и нулём внутри записи; заодно измеряется конец
                          входа у интерпретатора (./sonder reclen-test)
  срабатывание свода      службой, считающей свод при старте вместо
                          расписания (./sonder digest-schedule, нужен
                          поднятый состав)

ТЕКСТ

if [ "$rc" -ne 0 ]; then
  echo "ЕСТЬ ПРОВЕРКИ, КОТОРЫЕ НЕ УМЕЮТ ПАДАТЬ" >&2
else
  echo "все фальсификации сработали"
fi
exit "$rc"
