#!/usr/bin/env bash
# У каждой службы состава есть политика перезапуска.
#
# ЗАЧЕМ. Служба без политики живёт ровно до первого перезапуска демона
# Docker — а он случается: обновление Docker Desktop, перезагрузка
# машины, нехватка памяти. Наблюдалось на этом самом стенде: все
# контейнеры, включая чужих проектов, показали одинаковый `Exited (255)`
# без единой записи об ошибке, и вернулась только нода — единственная, у
# кого политика была. Человек в это время открыл адрес и увидел отказ
# соединения.
#
# ЧТО ЭТА ПРОВЕРКА ДОКАЗЫВАЕТ: политика объявлена в compose И применена
# к запущенному контейнеру. Второе не следует из первого — правка
# `docker-compose.yml` не касается уже поднятого состава, и здесь это
# сбило с толку: файл был исправлен, а контейнер работал по-старому.
#
# ЧЕГО НЕ ДОКАЗЫВАЕТ: что состав ВЕРНЁТСЯ. Убедиться в этом поведением
# локально нечем, и вот почему — оба очевидных способа не работают:
#
#   * `docker kill` снаружи Docker считает остановкой вручную и политику
#     к ней не применяет: контейнер остаётся лежать;
#   * сигнал изнутри пространства имён первому процессу ядро игнорирует
#     — даже SIGKILL. Вызов возвращает ноль и не делает ничего, то есть
#     проверка выглядела бы прошедшей, ничего не проверив.
#
# Остаётся перезапуск самого демона, а он унёс бы и чужие проекты на
# этой машине. Разрыв назван прямо, а не закрыт видимостью проверки.
set -uo pipefail

ROOT="$(cd "$(dirname "$0")/../../.." && pwd)"
cd "$ROOT" || exit 1

# Службы основного профиля. Наблюдаемость (`obs`) сюда не входит: её
# поднимают отдельной просьбой, и её отсутствие ничего не ломает.
SERVICES="db app node web"

rc=0

for service in $SERVICES; do
  declared="$(awk -v s="$service" '
    $0 ~ "^  " s ":" { inside = 1; next }
    inside && /^  [a-z]/ { inside = 0 }
    inside && /^    restart:/ { print; exit }
  ' docker-compose.yml)"

  if [ -z "$declared" ]; then
    echo "  $service: политики перезапуска НЕТ в docker-compose.yml"
    rc=1
    continue
  fi

  id="$(docker compose ps -q "$service" 2>/dev/null | head -1)"
  if [ -z "$id" ]; then
    echo "  $service: объявлена, но контейнер не запущен — применение не проверено"
    continue
  fi

  actual="$(docker inspect "$id" --format '{{.HostConfig.RestartPolicy.Name}}' 2>/dev/null)"
  if [ "$actual" != "unless-stopped" ]; then
    echo "  $service: в файле есть, у контейнера «$actual» —"
    echo "    состав поднят по старому файлу, нужен --force-recreate"
    rc=1
  fi
done

if [ "$rc" -eq 0 ]; then
  echo "  все службы объявляют политику, и запущенные её имеют"
fi
exit "$rc"
