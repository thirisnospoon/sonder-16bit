#!/usr/bin/env bash
# Умеют ли падать оба приговора замера лага.
#
# У замера их два: SLO по p99 и отдельный порог по медиане, стерегущий
# дверной звонок очереди. Второй появился потому, что первый не различал
# режимов: без звонка медиана 860 мс, а порог в секунду такое пропускал.
#
# ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ И ЧТО НЕТ. Проверяется, что каждый приговор
# выносится: недостижимый порог обязан дать ненулевой код. НЕ
# проверяется, что порог по медиане отличает живой звонок от мёртвого на
# настоящей системе — для этого нужен состав с выключенным звонком, и
# такая фальсификация лежит отдельно, среди требующих пересборки.
set -uo pipefail

ROOT="$(cd "$(dirname "$0")/../../.." && pwd)"
cd "$ROOT" || exit 1

# Три поста вместо пятнадцати: приговор проверяется, а не величина.
COUNT=3

bash ops/ci/lag.sh > /tmp/f-lag-0.log 2>&1 \
  || { echo "  БАЗА КРАСНАЯ"; sed -n '$p' /tmp/f-lag-0.log; exit 1; }

SONDER_LAG_COUNT="$COUNT" SONDER_LAG_SLO_MS=1 \
  bash ops/ci/lag.sh > /tmp/f-lag-1.log 2>&1 \
  && { echo "  ЗЕЛЕНО ПРИ НЕДОСТИЖИМОМ SLO"; exit 1; }
grep -aq "SLO НАРУШЕН" /tmp/f-lag-1.log \
  || { echo "  упало не на SLO"; exit 1; }

SONDER_LAG_COUNT="$COUNT" SONDER_LAG_DOORBELL_MS=1 \
  bash ops/ci/lag.sh > /tmp/f-lag-2.log 2>&1 \
  && { echo "  ЗЕЛЕНО ПРИ НЕДОСТИЖИМОМ ПОРОГЕ ЗВОНКА"; exit 1; }
grep -aq "ЗВОНОК ОЧЕРЕДИ НЕ РАБОТАЕТ" /tmp/f-lag-2.log \
  || { echo "  упало не на звонке"; exit 1; }

echo "  оба приговора выносятся и называют себя"
