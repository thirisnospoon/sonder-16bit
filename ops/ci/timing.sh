#!/usr/bin/env bash
# Выдаёт ли время ответа существование ника.
#
# THREAT-MODEL.md называет это средством защиты от перечисления
# пользователей и честно помечает: обеспечено конструкцией, но НЕ
# измерено. Конструкция такая: пароль проверяется ВСЕГДА, даже когда
# пользователя нет, — против фиктивного хэша той же стоимости.
#
# ЧТО ИЩЕМ. Не тонкую статистическую разницу, а обвал: если фиктивный
# хэш убрать, несуществующий ник перестанет платить за bcrypt стоимости
# 12, и ответ станет быстрее примерно на сто миллисекунд. Именно так и
# выглядит настоящая регрессия — не «на два процента», а «вдвое».
#
# ПОЭТОМУ ПОРОГ ГРУБЫЙ, и это осознанно. Тонкий порог на замере, где
# каждый запрос платит за свежее TLS-рукопожатие, давал бы ложные
# срабатывания — а проверка, падающая раз в двадцать прогонов, сообщает
# о системе ровно то же, что и не падающая никогда.
#
# ЗАМЕРЫ ЧЕРЕДУЮТСЯ. Машина за время прогона греется, тормозит соседним
# контейнером и меняет частоту; два блока подряд сравнивали бы не ветки
# кода, а начало прогона с концом.
#
# ПО ОДНОЙ ПОПЫТКЕ НА НИК. Предел частоты входа — десять неудач за
# четверть часа, и упереться в него посреди замера значило бы мерить
# скорость отказа 429, а она одинакова для обеих веток и потому
# бессмысленна здесь.
#
# Имена переменных латиницей.
set -uo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
URL="${SONDER_URL:-https://localhost:8443}"
PASSWORD='достаточно-длинный-пароль'

# Сколько пар замеров.
PAIRS="${SONDER_TIMING_PAIRS:-40}"

# Порог: во сколько раз медианы могут различаться, в процентах от
# меньшей. Двадцать процентов от ~130 мс — это 26 мс, вчетверо меньше
# цены bcrypt и вчетверо больше разброса TLS-рукопожатия.
MAX_DIFF_PCT="${SONDER_TIMING_MAX_PCT:-20}"

cd "$ROOT" || exit 1

fail() { echo; echo "ПРОВАЛ: $*" >&2; exit 1; }

now_ms() { echo $(( $(date +%s%N) / 1000000 )); }

STAMP="$(date +%s | tail -c 6)$RANDOM"

echo "==> время ответа входа: существующий ник против несуществующего"
echo "  пар замеров: $PAIRS"

echo "  готовим $PAIRS учётных записей…"
for i in $(seq 1 "$PAIRS"); do
  CODE="$(curl -sk -o /dev/null -w '%{http_code}' -X POST "$URL/api/users" \
          -H 'Content-Type: application/json' \
          -d "{\"nick\":\"t${STAMP}e$i\",\"displayName\":\"Есть\",\"password\":\"$PASSWORD\"}")"
  [ "$CODE" = 201 ] || fail "регистрация t${STAMP}e$i ответила $CODE"
done

попытка() {
  local nick="$1" start
  start="$(now_ms)"
  curl -sk -o /dev/null -X POST "$URL/api/auth/login" \
    -H 'Content-Type: application/json' \
    -d "{\"nick\":\"$nick\",\"password\":\"заведомо неверный пароль\"}"
  echo $(( $(now_ms) - start ))
}

EXISTING=""
MISSING=""
for i in $(seq 1 "$PAIRS"); do
  EXISTING="$EXISTING $(попытка "t${STAMP}e$i")"
  MISSING="$MISSING $(попытка "t${STAMP}x$i")"
done

медиана() {
  echo "$1" | tr ' ' '\n' | grep -v '^$' | sort -n \
    | awk '{ v[NR] = $1 } END { print v[int((NR + 1) / 2)] }'
}
размах() {
  echo "$1" | tr ' ' '\n' | grep -v '^$' | sort -n \
    | awk '{ v[NR] = $1 }
           END { print v[int(NR * 3 / 4)] - v[int(NR / 4) + 1] }'
}

ME="$(медиана "$EXISTING")"
MM="$(медиана "$MISSING")"
RE="$(размах "$EXISTING")"
RM="$(размах "$MISSING")"

DIFF=$(( ME > MM ? ME - MM : MM - ME ))
MIN=$(( ME < MM ? ME : MM ))
PCT=$(( MIN > 0 ? DIFF * 100 / MIN : 999 ))

echo
printf '  существующий ник   медиана %4d мс, межквартильный размах %3d мс\n' "$ME" "$RE"
printf '  несуществующий     медиана %4d мс, межквартильный размах %3d мс\n' "$MM" "$RM"
printf '  разница медиан     %4d мс, это %d%% (порог %d%%)\n' "$DIFF" "$PCT" "$MAX_DIFF_PCT"
echo

if [ "$PCT" -ge "$MAX_DIFF_PCT" ]; then
  echo "ВРЕМЯ ОТВЕТА ВЫДАЁТ СУЩЕСТВОВАНИЕ НИКА." >&2
  echo "Проверка пароля должна идти и для несуществующего пользователя —" >&2
  echo "против фиктивного хэша ТОЙ ЖЕ стоимости." >&2
  exit 1
fi

echo "время ответа не различает существующий ник и несуществующий"
