#!/usr/bin/env bash
# Свод на эталонных данных: итоги известны заранее.
#
# ЗАЧЕМ. До этой проверки числа свода подтверждались тем, что на них
# посмотрели и они выглядели правдоподобно. Так уже трижды выглядели
# неправдоподобные: 90 300 байт на пост и 6,74 байта на символ прошли
# именно этот способ проверки — глазами.
#
# ЧТО СТЕРЕЖЁТСЯ, помимо сложения:
#
#   * ПОСЛЕДНЯЯ ГРУППА. Контрольный переход срабатывает на СМЕНЕ автора,
#     а после последней записи менять нечего. Забытый итог последнего
#     автора — классическая потеря в этом приёме, и выглядит она как
#     «одного автора просто нет», а не как ошибка;
#   * группа из ОДНОГО элемента: она ломается иначе, чем группа из
#     многих;
#   * байты против символов: в эталоне есть и чистая латиница, где они
#     равны, и удвоение — перепутанные колонки иначе не поймать.
set -uo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
IMAGE=sonder/report:1
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

cd "$ROOT" || exit 1

fail() { echo; echo "ПРОВАЛ: $*" >&2; exit 1; }

docker image inspect "$IMAGE" > /dev/null 2>&1 \
  || docker build -f ops/compose/Dockerfile.report -t "$IMAGE" . > /dev/null \
  || fail "не собрать образ свода"

echo "==> эталонный вход"
docker run --rm -v "$ROOT:/work" -v "$WORK:/out" -w /work sonder/contracts:1 \
  python report/test/make-fixture.py /out/posts.dat \
  || fail "не построить эталонный вход"

echo
echo "==> свод"
docker run --rm \
  -v "$WORK:/data" \
  -e SONDER_DIGEST_INPUT=/data/posts.dat \
  -e SONDER_DIGEST_OUTPUT=/data/digest.txt \
  "$IMAGE" \
  || fail "пакет отказал"

REPORT="$WORK/digest.txt"
[ -s "$REPORT" ] || fail "отчёт пуст"

echo
cat "$REPORT"
echo

# Ожидаемое посчитано в report/test/make-fixture.py и повторено здесь
# НАМЕРЕННО: проверка, берущая ожидание из того же места, что и вход,
# подтверждает лишь, что два вычисления совпали. Числа ниже написаны
# рукой и проверяются глазами один раз — при чтении этого файла.
echo "==> сверка"
grep -qE '^  alpha +3 +60 +60 *$' "$REPORT" \
  || fail "строка alpha не та: $(grep -a alpha "$REPORT")"
echo "  alpha: 3 поста, 60 байт, 60 символов — сходится"

grep -qE '^  beta +1 +7 +7 *$' "$REPORT" \
  || fail "строка beta не та: $(grep -a beta "$REPORT")"
echo "  beta: группа из одного поста — сходится"

# ГЛАВНОЕ: gamma последняя, и её итог печатается только если программа
# не забыла закрыть последнюю группу.
grep -qE '^  gamma +2 +300 +150 *$' "$REPORT" \
  || fail "строка gamma не та или потеряна — последняя группа не закрыта"
echo "  gamma (последняя группа) — на месте"

grep -qE 'ИТОГО +6 +367 +217 *$' "$REPORT" \
  || fail "общий итог не тот: $(grep -a ИТОГО "$REPORT")"
echo "  ИТОГО 6 постов, 367 байт, 217 символов — сходится"

grep -qE 'АВТОРОВ +3 *$' "$REPORT" \
  || fail "число авторов не то: $(grep -a АВТОРОВ "$REPORT")"
echo "  авторов 3 — сходится"

# 367 / 217 = 1.6912..., COBOL печатает с двумя знаками.
grep -qE 'БАЙТ НА СИМВОЛ +1\.69 *$' "$REPORT" \
  || fail "байт на символ не тот: $(grep -a СИМВОЛ "$REPORT")"
echo "  байт на символ 1.69 — сходится"

echo
echo "свод считает верно на эталонных данных"
