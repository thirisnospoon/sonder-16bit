#!/usr/bin/env bash
# Сквозной след: от запроса из браузера до строки лога NODE-7.
#
# Гейт Ф10 требует, чтобы ОДИН `trace_id` прослеживался через всю
# систему. Проверяется это единственным осмысленным способом — пройти её
# насквозь и предъявить один и тот же идентификатор в четырёх местах:
#
#   1. заголовок ответа  — его знает вызвавший, то есть браузер;
#   2. журнал оболочки   — Java, HTTP, база, outbox;
#   3. файл NODE-7       — шестнадцать бит под эмулятором DOS;
#   4. канал журнала     — та же запись, но NDJSON-ом по линии, в общем
#                          потоке с оболочкой;
#   5. строка outbox     — там след живёт дольше всех: журналы
#                          ротируются, событие остаётся.
#
# ЗАЧЕМ ТАКАЯ ПРОВЕРКА ВООБЩЕ. Части живут в разных мирах, и «что
# случилось с ЭТИМ запросом» без общего идентификатора решается
# сличением времён: команд десяток в секунду, часы под эмулятором свои,
# а лог ядра пишется в файл внутри эмулированного диска. Сличение тут не
# метод, а гадание.
#
# ИМЕНА ПЕРЕМЕННЫХ ЛАТИНИЦЕЙ. Кириллица в идентификаторе bash — не
# ошибка присваивания, а «command not found»: строка перестаёт быть
# присваиванием и становится вызовом команды, скрипт продолжает
# работать, а переменная остаётся пустой. Тот же капкан уже испортил
# точку входа ноды.
#
# Проверка идёт против ПОДНЯТОЙ системы и умеет провалиться на каждом из
# пяти мест по отдельности.
set -uo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
URL="${SONDER_URL:-https://localhost:8443}"
PAUSE="${SONDER_TRACE_PAUSE:-4}"
DB_PASSWORD="${SONDER_DB_PASSWORD:-masterkey}"

cd "$ROOT" || exit 1

fail() { echo; echo "ПРОВАЛ: $*" >&2; exit 1; }

echo "==> сквозной след через $URL"

# --- Свой человек: команда должна дойти до ядра, а не упереться в 401 --
NICK="tr$(date +%s | tail -c 7)$RANDOM"
PASSWORD='достаточно-длинный-пароль'
COOKIES="$(mktemp)"
HEADERS="$(mktemp)"
trap 'rm -f "$COOKIES" "$HEADERS"' EXIT

CODE="$(curl -sk -o /dev/null -w '%{http_code}' -X POST "$URL/api/users" \
        -H 'Content-Type: application/json' \
        -d "{\"nick\":\"$NICK\",\"displayName\":\"След\",\"password\":\"$PASSWORD\"}")"
[ "$CODE" = 201 ] || fail "регистрация ответила $CODE"

CODE="$(curl -sk -o /dev/null -w '%{http_code}' -c "$COOKIES" \
        -X POST "$URL/api/auth/login" \
        -H 'Content-Type: application/json' \
        -d "{\"nick\":\"$NICK\",\"password\":\"$PASSWORD\"}")"
[ "$CODE" = 204 ] || fail "вход ответил $CODE"

# --- Команда, ради которой всё и затевается ---------------------------
# Пост идёт ЧЕРЕЗ ЯДРО: оболочка спрашивает решение по линии, ядро
# отвечает, событие уезжает в outbox. Чтение так не ходит и следа в ядре
# не оставляет — проверять надо именно команду.
CODE="$(curl -sk -o /dev/null -D "$HEADERS" -w '%{http_code}' -b "$COOKIES" \
        -X POST "$URL/api/posts" \
        -H 'Content-Type: application/json' \
        -d '{"body":"Пост ради следа"}')"
[ "$CODE" = 201 ] || { cat "$HEADERS" >&2; fail "создание поста ответило $CODE"; }

TRACE="$(tr -d '\r' < "$HEADERS" | awk 'tolower($1) == "x-trace-id:" { print $2 }')"
[ -n "$TRACE" ] || fail "в ответе нет заголовка X-Trace-Id — вызвавшему след неизвестен"

echo "  след: $TRACE"

# Ядро успевает ответить раньше, чем вернётся HTTP, — иначе пост не был
# бы создан. Пауза нужна не ядру, а tail-у, который переносит журнал
# эмулятора в вывод контейнера.
sleep "$PAUSE"

# --- 1. Журнал оболочки -----------------------------------------------
if docker compose logs app 2>&1 | grep -aq -- "$TRACE"; then
  echo "  оболочка: есть"
  docker compose logs app 2>&1 | grep -a -- "$TRACE" | head -3 | sed 's/^/      /'
else
  fail "следа нет в журнале оболочки"
fi

# --- 2. Журнал NODE-7: файл на диске эмулятора ------------------------
if docker compose logs node 2>&1 | grep -aq -- "$TRACE"; then
  echo "  NODE-7: есть"
  docker compose logs node 2>&1 | grep -a -- "$TRACE" | head -3 | sed 's/^/      /'
else
  echo "  журнал ядра, последние строки:" >&2
  docker compose exec -T node tail -5 /node/NODE7.LOG 2>&1 | sed 's/^/      /' >&2
  fail "следа нет в журнале NODE-7 — цепочка обрывается на линии"
fi

# --- 3. Структурный журнал ядра ---------------------------------------
#
# Ядро шлёт запись о решении NDJSON-ом отдельным каналом мультиплексора,
# и в ней тот же след. Это отдельная от файла дорога: файл переживает
# обрыв линии, а канал доносит запись туда, где её видно вместе со
# строками оболочки.
#
# Проверяется ИМЕННО КАНАЛ, а не файл: подключён он был последним, и
# отвалиться может молча — записи просто перестанут приходить, а система
# останется исправной.
if docker compose logs app 2>&1 | grep -a "NODE-7 {" | grep -aq -- "$TRACE"; then
  echo "  структурный журнал ядра: есть"
  docker compose logs app 2>&1 | grep -a "NODE-7 {" | grep -a -- "$TRACE"     | head -1 | sed 's/^/      /'
else
  echo "  последние записи ядра по каналу:" >&2
  docker compose logs app 2>&1 | grep -a "NODE-7 {" | tail -3 >&2
  fail "следа нет в структурном журнале ядра: канал журнала не доносит"
fi

# --- 4. Строка события в outbox ---------------------------------------
# Берётся ЧИСТО ЧИСЛОВАЯ строка ответа, а не все цифры подряд. `isql`
# при отказе печатает текст с номерами кодов, и вычёркивание всего
# нецифрового превратило бы жалобу «нет такой таблицы» в убедительное
# число строк. Проверка, которую можно обмануть текстом ошибки, зеленеет
# ровно тогда, когда должна краснеть.
ROWS="$(printf "SELECT COUNT(*) FROM outbox WHERE trace_id = '%s';\n" "$TRACE" \
        | docker compose exec -T db isql -b -q \
            -user sysdba -password "$DB_PASSWORD" \
            /var/lib/firebird/data/sonder.fdb 2>&1 \
        | awk '/^[[:space:]]*[0-9]+[[:space:]]*$/ { n = $1 } END { print n + 0 }')"
if [ "${ROWS:-0}" -ge 1 ]; then
  echo "  outbox: есть, строк $ROWS"
else
  fail "следа нет в outbox — событие потеряло связь с командой"
fi

echo
echo "след $TRACE прошёл всю систему:"
echo "  заголовок → оболочка → файл NODE-7 → канал журнала → outbox"
