"""
Граф модулей Pascal: без циклов и без рёбер вверх.

ЭТО ПАСКАЛЕВСКИЙ ДВОЙНИК ArchUnit. Для Java правило «домен не знает о
Spring, JDBC и JAX-WS» проверяется тестом и проверено на намеренных
нарушителях. Для Pascal — где домен и живёт (ADR-0011) — такого же
правила не было, хотя именно здесь оно и главное: ЯДРО ЕСТЬ ЧИСТАЯ
ФУНКЦИЯ, и ввода-вывода в нём нет по построению.

«По построению» — это утверждение, и до этой проверки его ничто не
подкрепляло. Достаточно было дописать `TcPort` в `uses` доменного
модуля, чтобы ядро начало читать порт; собралось бы молча.

ЧЕТЫРЕ СЛОЯ, и рёбра между ними разрешены только вниз:

    node7      программа: связывает всё, сама не решает ничего
    domain     правила: чистые функции над записями контракта
    generated  типы и разборщик из контрактов
    turbocore  фреймворк: не знает ни о домене, ни о контрактах

Домену при этом мало «не выше»: ему запрещены и те модули фреймворка,
что означают ввод-вывод, планирование и разбор конвертов. Список
разрешённого — белый, а не чёрный: новый модуль фреймворка не должен
становиться доступным домену молча.
"""
import re
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]
ИСХОДНИКИ = КОРЕНЬ / "dosnode" / "src"

# Модули RTL и целевой платформы. Их приносит компилятор, и слоями они
# не управляются.
RTL = {"ports", "dos", "crt", "strings", "sysutils", "system"}

СЛОИ = {"turbocore": 0, "generated": 1, "domain": 2, "node7": 3}

# Что домену разрешено из фреймворка. Чистые вычисления и память — да;
# порт, кольцо, планировщик, разбор конвертов — нет.
ДОМЕНУ_МОЖНО = {"tcresult", "tcstr", "tcarena", "tclog"}


def слой(путь: Path) -> str:
    родитель = путь.parent.name
    if родитель in СЛОИ:
        return родитель
    if путь.stem.lower() == "node7":
        return "node7"
    raise ValueError(f"не понять, какому слою принадлежит {путь}")


def зависимости(текст: str) -> set[str]:
    """Имена из ВСЕХ `uses`: и в интерфейсе, и в реализации.

    Второй `uses` — не редкость: `tcport` берёт RTL-модуль `Ports`
    только в реализации. Проверка, читающая один, пропускала бы ровно
    те зависимости, которые прячут.
    """
    из: set[str] = set()
    for м in re.finditer(r"^\s*uses\b(.*?);", текст, re.M | re.S | re.I):
        for имя in м.group(1).split(","):
            имя = имя.strip().split("{")[0].strip()
            if имя:
                из.add(имя.lower())
    return из


def main() -> int:
    модули: dict[str, tuple[str, set[str]]] = {}
    for путь in sorted(ИСХОДНИКИ.rglob("*.pas")):
        текст = путь.read_text(encoding="utf-8")
        # Комментарии выкидываем: в них встречаются и слово uses, и
        # имена модулей, которых в коде нет.
        без_комментариев = re.sub(r"\{.*?\}", " ", текст, flags=re.S)
        модули[путь.stem.lower()] = (слой(путь), зависимости(без_комментариев))

    провалы: list[str] = []

    for имя, (свой, деп) in sorted(модули.items()):
        for цель in sorted(деп):
            if цель in RTL:
                continue
            if цель not in модули:
                провалы.append(
                    f"{имя}: зависит от «{цель}», которого нет ни среди "
                    f"модулей, ни в списке RTL. Либо модуль потерян, "
                    f"либо список RTL устарел"
                )
                continue
            чужой = модули[цель][0]
            if СЛОИ[чужой] > СЛОИ[свой]:
                провалы.append(
                    f"РЕБРО ВВЕРХ: {имя} ({свой}) → {цель} ({чужой})"
                )
            if свой == "domain" and чужой == "turbocore" \
                    and цель not in ДОМЕНУ_МОЖНО:
                провалы.append(
                    f"ДОМЕН ТРОГАЕТ {цель}: ядро есть чистая функция, "
                    f"ввода-вывода и планирования в нём нет по построению "
                    f"(ADR-0011). Разрешено домену: "
                    f"{', '.join(sorted(ДОМЕНУ_МОЖНО))}"
                )

    # Циклы. FPC отвергает циклическую зависимость интерфейсов сам, но
    # правило записано в ENGINEERING.md, а записанное правило обязано
    # быть проверкой, а не пожеланием: реализации FPC циклы разрешает.
    цвет: dict[str, int] = {}

    def обойти(имя: str, путь: list[str]) -> None:
        цвет[имя] = 1
        for цель in sorted(модули[имя][1]):
            if цель not in модули:
                continue
            if цвет.get(цель) == 1:
                кольцо = путь[путь.index(цель):] if цель in путь else [цель]
                провалы.append("ЦИКЛ: " + " → ".join(кольцо + [цель]))
            elif цвет.get(цель, 0) == 0:
                обойти(цель, путь + [цель])
        цвет[имя] = 2

    for имя in sorted(модули):
        if цвет.get(имя, 0) == 0:
            обойти(имя, [имя])

    print()
    print("==============================================")
    print(" Граф модулей Pascal")
    print("==============================================")
    for слой_имя in sorted(СЛОИ, key=lambda s: СЛОИ[s]):
        свои = [и for и, (с, _) in модули.items() if с == слой_имя]
        print(f"  {слой_имя:<12} модулей {len(свои):>2}: "
              f"{', '.join(sorted(свои))}")
    print()

    if провалы:
        for п in провалы:
            print(f"ПРОВАЛ: {п}", file=sys.stderr)
        return 1
    print(f"рёбер вверх нет, циклов нет; модулей {len(модули)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
