"""
Бюджеты из TURBOCORE.md §12 против констант кода.

ЗАЧЕМ. Таблица бюджетов помечает три строки словами «проверка в CI», и
проверки этой не существовало ни для одной: бюджет жил утверждением.
Нашлось это сверкой таблицы гейтов с действительностью — не превышением,
а чтением, — и это ровно тот случай, ради которого сверку и делают.

Бюджет без проверки хуже отсутствующего. Отсутствующий вынуждает думать
при каждом изменении; заявленный и непроверяемый создаёт уверенность,
что кто-то следит.

ЧИСЛА БЕРУТСЯ ИЗ ТАБЛИЦЫ, А НЕ ПОВТОРЯЮТСЯ ЗДЕСЬ. Повторённые, они
разошлись бы с документом молча — тот же класс дефекта, что и список
файлов, вписанный в проверку вторым экземпляром (см. `check-eol`).
Строка, которую не удалось разобрать, ЛОМАЕТ проверку: переименованный
бюджет обязан быть замечен, а не тихо выпасть из-под контроля.
"""
import re
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]
ДОКУМЕНТ = КОРЕНЬ / "docs" / "TURBOCORE.md"


def бюджеты() -> dict[str, str]:
    """Строки таблицы §12: название ресурса → колонка «Бюджет»."""
    текст = ДОКУМЕНТ.read_text(encoding="utf-8")
    начало = текст.index("## 12. Бюджеты")
    конец = текст.index("## 13.", начало)
    из = {}
    for строка in текст[начало:конец].splitlines():
        части = [ч.strip() for ч in строка.split("|")]
        # | Ресурс | Бюджет | Контроль |  → пять частей с пустыми краями
        if len(части) < 4 or части[1] in ("", "Ресурс", "---"):
            continue
        if set(части[2]) <= set("-: "):
            continue
        из[части[1]] = части[2]
    return из


def число(текст: str) -> int:
    """Первое целое из строки бюджета. «**512 байт** …» → 512."""
    м = re.search(r"(\d[\d  ]*)", текст.replace("**", ""))
    if м is None:
        raise ValueError(f"в бюджете нет числа: {текст!r}")
    return int(м.group(1).replace(" ", "").replace(" ", ""))


def константа(файл: str, имя: str) -> int:
    """Значение константы Pascal. Только числовые: выражения не считаем."""
    путь = КОРЕНЬ / файл
    текст = путь.read_text(encoding="utf-8")
    м = re.search(rf"^\s*{re.escape(имя)}\s*=\s*(\d+)\s*;", текст, re.M)
    if м is None:
        raise ValueError(f"в {файл} нет числовой константы {имя}")
    return int(м.group(1))


def main() -> int:
    таблица = бюджеты()
    провалы: list[str] = []
    отчёт: list[tuple[str, str, str]] = []

    def сверить(строка_бюджета: str, что: str, значение: int,
                предел: int | None = None) -> None:
        if строка_бюджета not in таблица:
            провалы.append(
                f"в TURBOCORE.md §12 нет строки «{строка_бюджета}» — "
                f"бюджет переименован или удалён, и проверка ослепла"
            )
            return
        объявлено = предел if предел is not None else число(таблица[строка_бюджета])
        годно = значение <= объявлено
        отчёт.append((что, f"{значение} из {объявлено}", "" if годно else "ПРЕВЫШЕН"))
        if not годно:
            провалы.append(
                f"{что}: {значение} против бюджета {объявлено} "
                f"(«{строка_бюджета}»)"
            )

    # Команд одновременно — это число каналов мультиплексора, и оно же
    # число файберов планировщика: семнадцатая команда получает отказ.
    сверить("Команд одновременно", "каналов мультиплексора",
            константа("dosnode/src/turbocore/tcsched.pas", "MaxFibers"))

    # Полезная нагрузка кадра. Измерена S2: больше — дольше занятие
    # линии, меньше — доля накладных растёт.
    сверить("Размер кадра", "полезная нагрузка кадра, Б",
            константа("dosnode/src/turbocore/tcframe.pas", "MaxPayload"))

    # Арены каналов вместе. Бюджет объявлен на команду, а расходуется
    # на все каналы разом — их столько же, сколько команд.
    каналов = константа("dosnode/src/turbocore/tcsched.pas", "MaxFibers")
    на_канал = константа("dosnode/src/node7.pas", "ArenaPerChan")
    предел_кб = число(таблица.get("Арена на команду", "33"))
    сверить("Арена на команду", "арены всех каналов, Б",
            каналов * на_канал, предел_кб * 1024)

    print()
    print("==============================================")
    print(" Бюджеты TURBOCORE §12 против кода")
    print("==============================================")
    for что, значение, метка in отчёт:
        print(f"  {что:<32} {значение:>16}  {метка}")
    print()

    if провалы:
        for п in провалы:
            print(f"ПРОВАЛ: {п}", file=sys.stderr)
        return 1
    print("бюджеты соблюдены")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
