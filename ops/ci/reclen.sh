#!/usr/bin/env bash
# Длина записей свода, проверенная вторым мнением — программой на
# Brainfuck в отдельном контейнере.
#
# ЗАЧЕМ ВТОРОЕ МНЕНИЕ. Первая проверка длины была на awk и была НЕВЕРНА:
# `length()` считает СИМВОЛЫ при многобайтовой локали, и запись в 380
# байт с шестью кириллическими буквами давала 374 — проверка объявила
# негодными 6971 запись из 6972 при исправной выгрузке. За ту же сессию
# единицу измерения перепутали четырежды: в RPAD Firebird, в PIC
# копибука, в колонках COBOL, в awk.
#
# Общее у всех четырёх — понятие «символ». Проверяющий, который делит
# это понятие с проверяемым, разделит с ним и ошибку. У интерпретатора
# Brainfuck понятия «символ» нет вовсе: он читает байт и прибавляет
# единицу. Ошибиться в единице измерения ему нечем (ADR-0019).
#
# ЭТОТ ФАЙЛ — ТОЛЬКО ДОСТАВКА. Сам вердикт живёт в
# ops/compose/reclen-verdict.sh и зовётся отсюда, потому что ту же
# проверку проходит НОЧНАЯ выгрузка, у которой интерпретатор лежит
# внутри её собственного образа. Дороги две, вопрос один, и ответ на
# него обязан быть один: две копии вердикта разошлись бы молча — только
# на испорченных данных, то есть в тот единственный раз, когда нужны.
#
# ОБРАЗ ПОМЕЧЕН ОТПЕЧАТКОМ ПРОГРАММЫ, а не версией. `docker image
# inspect` отвечает «есть» и на образ, собранный до правки программы:
# проверка продолжила бы работать по старой редакции и осталась бы
# зелёной ровно тогда, когда должна покраснеть. Отпечаток в теге делает
# устаревший образ ДРУГИМ образом, и его просто нет.
set -uo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
FILE="${1:?нужен путь к файлу выгрузки}"

cd "$ROOT" || exit 1

fail() { echo "ПРОВАЛ: $*" >&2; exit 1; }

FINGERPRINT="$(sha1sum report/src/reclen.bf | cut -c1-12)"
IMAGE="sonder/reclen:$FINGERPRINT"

if ! docker image inspect "$IMAGE" > /dev/null 2>&1; then
  docker build -q -f ops/compose/Dockerfile.bf -t "$IMAGE" . > /dev/null \
    || fail "не собрать образ проверки длины"
fi

# Прежние отпечатки за собой убираются. Плата за тег-отпечаток — новый
# образ на каждую правку программы, по 120 МБ; за неделю работы над
# разметкой их набралось бы полтора десятка.
#
# Уборка стоит СНАРУЖИ ветки сборки, а не внутри. Внутри она не
# срабатывала: образ успевал собрать вызывающий (так делает
# reclen-test.sh, которому образ нужен для замера конца входа), ветка не
# выполнялась, и старые отпечатки оставались лежать.
#
# Удаляются ТОЛЬКО теги sonder/reclen, кроме текущего: этот образ заводит
# этот же скрипт, собирается он за секунды из Dockerfile, и ничего кроме
# кеша сборки в нём нет. Отказ удаления не беда — образ может быть занят
# контейнером, и это не повод ронять проверку.
docker images --filter=reference='sonder/reclen' \
              --format '{{.Repository}}:{{.Tag}}' 2>/dev/null \
  | grep -v -x -F "$IMAGE" \
  | xargs -r docker rmi > /dev/null 2>&1 || true

bash ops/compose/reclen-verdict.sh \
  "$FILE" contracts/reports/digest-v1.yaml \
  docker run --rm -i "$IMAGE"
