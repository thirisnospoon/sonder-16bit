"""
Имена переменных в shell-скриптах — только латиницей.

ЗАЧЕМ ЭТА ПРОВЕРКА СУЩЕСТВУЕТ. Кириллица в имени переменной bash — не
ошибка присваивания, а «command not found»: строка перестаёт быть
присваиванием и становится вызовом команды, скрипт ПРОДОЛЖАЕТ работать,
а переменная остаётся пустой.

В проекте, где комментарии, сообщения и имена в Pascal, Java и
TypeScript написаны кириллицей, это ловушка рефлекса. Она сработала пять
раз:

  * точка входа ноды — ожидание порта молча превратилось в ноль попыток,
    и эмулятор поднялся в пустоту;
  * ops/ci/trace.sh — все переменные разом;
  * ops/ci/chaos.sh — local с двумя кириллическими именами;
  * ops/ci/falsify/run.sh — объявила несуществующими все три
    фальсификации сразу;
  * скрипт-однодневка, создавший файл с пустым именем.

Знание правила не спасло ни разу: оно записано и в память, и в шапки
самих скриптов. Спасает только механика — риск R11 в RISKS.md о том же.

ЧТО ЛОВИТСЯ, А ЧТО НЕТ. Границу провело измерение, а не догадка. В
bash 5.3:

    ИМЯ=значение      -> «command not found», чтение -> «bad substitution»
    local начало=5    -> «not a valid identifier»
    попытка() { ... } -> РАБОТАЕТ, и возвращает значения как обычно

Поэтому ловятся присваивания и объявления local/export/readonly, а
имена функций — нет. Первая редакция ловила и функции, и сразу нашла три
«нарушения» в работающем замере: проверка, краснеющая на исправном коде,
учит себя игнорировать, а это хуже её отсутствия.

Комментарии, строки и сообщения не трогаются вовсе: кириллица в них —
норма проекта.

Ошибка присваивания при этом ГРОМКАЯ — печатается в stderr, — но не
останавливает скрипт: он идёт дальше с пустой переменной, и на фоне
прочего вывода строка теряется. Так все пять случаев и прожили до
последствий.
"""
import re
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[2]

# Имя перед знаком равенства. Класс символов нарочно широкий — любое
# непробельное без метасимволов, — потому что искомое как раз то, что
# в допустимые имена НЕ входит.
ПРИСВАИВАНИЕ = re.compile(
    r"^\s*(?:local\s+|export\s+|readonly\s+|declare\s+)?([^\s=;&|<>()'\"]+)="
)

# `local a b c` без знака равенства объявляет несколько имён сразу.
ОБЪЯВЛЕНИЕ = re.compile(r"^\s*(?:local|export|readonly|declare)\s+(.+)$")

# То же, но ГДЕ УГОДНО в строке: `f() { local начало=5; ... }` — целиком
# на одной строке — образцом с привязкой к началу не ловится, и первая
# редакция проверки его пропускала. Ищется только после ключевого слова
# объявления: искать присваивания в любом месте строки значило бы
# натыкаться на них внутри кавычек.
ОБЪЯВЛЕНИЕ_ВНУТРИ = re.compile(
    r"\b(?:local|export|readonly|declare)\s+([^\s=;&|<>()'\"]+)="
)

КОММЕНТАРИЙ = re.compile(r"^\s*#")

# Каталоги, куда ходить незачем: чужой код и порождённое.
МИМО = {".git", "node_modules", "target", "build", "dist",
        "test-results", "lighthouse", "out", "playwright-report"}


def не_ascii(имя: str) -> bool:
    return any(ord(c) > 127 for c in имя)


def в_кавычках(строка: str, место: int) -> bool:
    """Стоит ли найденное внутри строкового литерала.

    Нужно затем, что скрипт может ПИСАТЬ shell-код — так делают
    фальсификации, создающие пробники, — и объявление внутри кавычек не
    выполняется, а печатается. Первая редакция этого не различала и
    краснела на собственной фальсификации: проверка, ругающаяся на
    исправный код, учит себя игнорировать.

    Считаются кавычки ДО места находки: нечётное число означает, что
    находка внутри незакрытой пары. Многострочных литералов это не
    покрывает, и покрывать не берётся — для того нужен разборщик языка,
    а не проверка на тридцать строк.
    """
    начало = строка[:место]
    return начало.count("'") % 2 == 1 or начало.count('"') % 2 == 1


def файлы() -> list:
    """Обход дерева, а не `git ls-files`.

    Git тут не нужен и вреден: его нет в образе, где идут прочие
    проверки на Python, а его экранирование не-ASCII путей уже однажды
    создало дыру в соседней проверке — она молча не видела файлов с
    русскими именами. Обход файловой системы про экранирование не знает
    и видит в том числе НОВЫЕ файлы, ещё не добавленные в индекс: для
    проверки, обязанной ловить дефект ДО коммита, это существенно.
    """
    из = []
    for путь in sorted(КОРЕНЬ.rglob("*")):
        if any(часть in МИМО for часть in путь.parts):
            continue
        if not путь.is_file():
            continue
        if путь.suffix == ".sh" or путь.name == "sonder":
            из.append(путь)
    return из


def проверить(путь: Path) -> list:
    беды = []
    текст = путь.read_text(encoding="utf-8", errors="replace")
    for номер, строка in enumerate(текст.splitlines(), 1):
        if КОММЕНТАРИЙ.match(строка):
            continue

        м = ПРИСВАИВАНИЕ.match(строка)
        if м and не_ascii(м.group(1)):
            беды.append("{}:{}: переменная «{}»".format(
                путь.relative_to(КОРЕНЬ), номер, м.group(1)))
            continue

        найдено = False
        for м in ОБЪЯВЛЕНИЕ_ВНУТРИ.finditer(строка):
            if not не_ascii(м.group(1)):
                continue
            if в_кавычках(строка, м.start()):
                continue
            беды.append("{}:{}: объявление «{}»".format(
                путь.relative_to(КОРЕНЬ), номер, м.group(1)))
            найдено = True
        if найдено:
            continue

        м = ОБЪЯВЛЕНИЕ.match(строка)
        if м:
            for имя in re.split(r"[\s;]+", м.group(1)):
                имя = имя.split("=")[0].strip()
                if имя and не_ascii(имя):
                    беды.append("{}:{}: объявление «{}»".format(
                        путь.relative_to(КОРЕНЬ), номер, имя))
    return беды


def main() -> int:
    все = файлы()
    беды = [б for путь in все for б in проверить(путь)]

    print()
    print("    скриптов проверено: {}".format(len(все)))
    if беды:
        print("    имена переменных не латиницей. В bash это не ошибка")
        print("    присваивания, а «command not found»: скрипт продолжит")
        print("    с пустой переменной, и проверка станет пустой тоже:")
        for б in беды:
            print("      {}".format(б))
        return 1
    print("    имена переменных латиницей")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
