#!/usr/bin/env bash
# Срабатывает ли расписание ночного свода на самом деле.
#
# Проверяется ТОТ ЖЕ путь, которым свод пойдёт ночью: срок ставится на
# ближайшую минуту вперёд, и служба считает до него так же, как считала
# бы до трёх часов. Проверочного режима «каждые N секунд» в точке входа
# нет намеренно — он проверял бы ветку, которой ночью не существует.
#
# ДВЕ ПОЛОВИНЫ ПРОВЕРКИ, И ВТОРАЯ ВАЖНЕЕ ПЕРВОЙ:
#
#   1. отчёт ПОЯВЛЯЕТСЯ после наступления срока;
#   2. отчёт НЕ ПОЯВЛЯЕТСЯ до него.
#
# Без второй половины проверку прошла бы служба, которая считает свод
# один раз при старте и больше никогда. Выглядит это неотличимо: отчёт
# есть, контейнер жив, в журнале ни слова о беде. Именно так «ночной»
# снова стал бы названием.
#
# Против ПОДНЯТОГО состава: ./sonder up сначала. Базы тут довольно —
# свод не ходит ни в ядро, ни в проекцию.
set -uo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
OUT="${SONDER_REPORT_DIR:-$ROOT/report/out}"
REPORT="$OUT/digest.txt"

cd "$ROOT" || exit 1

fail() { echo; echo "ПРОВАЛ: $*" >&2; exit 1; }

docker compose ps db --format '{{.State}}' 2>/dev/null | grep -q running \
  || fail "состав не поднят: сначала ./sonder up"

# --- Рантайм Java внутри образа пакета ---------------------------------
#
# Образ собран из двух чужих: JRE взят из образа temurin и положен в
# Debian. Совместимость glibc тут снизу вверх и должна работать — но
# «должно» проверяется, а не предполагается: неподнявшийся рантайм иначе
# всплыл бы ночью, отказом выгрузки в пустом журнале.
echo "==> рантайм внутри бегунка"
VERSION="$(docker compose run --rm --no-deps --entrypoint java digest -version 2>&1)" \
  || fail "java в образе свода не запускается:
$VERSION"
echo "$VERSION" | head -1 | sed 's/^/  /'
echo "$VERSION" | grep -q '"1\.8' || fail "ожидалась Java 8, а получено иное"

# --- Конец входа у ЭТОГО интерпретатора --------------------------------
#
# Проверка длины записей едет в образе бегунка своим экземпляром beef, и
# программа опирается на измеренное поведение чтения за концом входа:
# соглашений три, языком оно не определено. Тот же замер делает
# ops/ci/reclen-test.sh, но НАД ДРУГИМ ОБРАЗОМ; пакеты в них могут
# разойтись, и разойдутся молча.
echo
echo "==> конец входа у интерпретатора внутри бегунка"
EOFOUT="$(docker compose run --rm --no-deps --entrypoint sh digest -c '
  printf "++++++++++[>++++++++++<-]>+++++.,." > /tmp/probe.bf
  beef /tmp/probe.bf < /dev/null | od -An -tu1 | tr -s " "
' 2>/dev/null)" || fail "проба конца входа не отработала"
if [ "$(echo "$EOFOUT" | tr -d ' \n\r')" = "105" ]; then
  echo "  чтение за концом входа прекращает программу — как и заложено"
else
  fail "интерпретатор в бегунке ведёт себя иначе: [$EOFOUT] вместо [105]"
fi

# --- Срок на ближайшую минуту вперёд -----------------------------------
#
# Две минуты, а не одна. Срок огрубляется до минуты, и «плюс минута»
# при 12:00:59 дало бы 12:01, до которого одна секунда: половина проверки
# про «не раньше срока» проверяла бы нечего. Две минуты дают до срока не
# меньше шестидесяти секунд при любом моменте запуска, а значит не меньше
# сорока пяти секунд тишины — за это время служба, считающая свод при
# старте, успевает выдать отчёт с большим запасом.
NOW=$(date -u +%s)
AT=$(date -u -d "@$((NOW + 120))" +%H:%M)
DUE=$(date -u -d "$(date -u -d "@$NOW" +%Y-%m-%d) $AT UTC" +%s)
SILENCE=$((DUE - NOW - 15))

echo
echo "==> срок $AT UTC, до него $((DUE - NOW)) с"

mkdir -p "$OUT"
rm -f "$REPORT"

# Срок возвращается к обычному, чем бы проверка ни кончилась. Иначе она
# оставила бы за собой службу, считающую свод в случайную минуту дня, —
# и это не сломалось бы, а просто стало бы неправдой относительно
# написанного в compose.
trap 'docker compose up -d --force-recreate digest > /dev/null 2>&1' EXIT

SONDER_DIGEST_AT="$AT" docker compose up -d --force-recreate digest > /dev/null 2>&1 \
  || fail "служба свода не поднялась"

# --- Половина первая: до срока тишина ----------------------------------
echo "  до срока отчёта быть не должно; жду $SILENCE с"
WAITED=0
while [ "$WAITED" -lt "$SILENCE" ]; do
  if [ -f "$REPORT" ]; then
    echo "  журнал службы:" >&2
    docker compose logs digest 2>&1 | tail -20 | sed 's/^/    /' >&2
    fail "отчёт появился через $WAITED с, за $((DUE - NOW - WAITED)) с до срока:
    служба считает свод при старте, а не по расписанию"
  fi
  sleep 5
  WAITED=$((WAITED + 5))
done
echo "  до срока тихо — расписание не подменено запуском при старте"

# --- Половина вторая: после срока отчёт --------------------------------
#
# Запас в полторы минуты после срока: выгрузка идёт по сети к базе, а
# пакет читает файл целиком. На пустой базе это доли секунды, на полной
# — секунды.
echo "  жду отчёта"
DEADLINE=$((DUE + 90))
while [ ! -f "$REPORT" ]; do
  if [ "$(date -u +%s)" -gt "$DEADLINE" ]; then
    echo "  журнал службы:" >&2
    docker compose logs digest 2>&1 | tail -20 | sed 's/^/    /' >&2
    fail "срок прошёл, отчёта нет"
  fi
  sleep 2
done

WHEN=$(date -u -d "@$(stat -c %Y "$REPORT")" +%FT%TZ)
echo "  отчёт появился: $WHEN"

# Отчёт обязан быть отчётом, а не пустым файлом: выгрузка могла отказать
# на середине, и пакет записал бы шапку без строк.
grep -qa 'ИТОГО' "$REPORT" || fail "в отчёте нет итоговой строки"
docker compose logs digest 2>&1 | grep -qa 'свод: готово' \
  || fail "служба не сообщила о завершении прогона"

# Ночная дорога обязана проходить ту же проверку длины, что и ручная.
# Пропущенная тут, она стерегла бы ровно ту из двух выгрузок, за которой
# и так смотрят глазами.
docker compose logs digest 2>&1 | grep -qa 'сверено на Brainfuck' \
  || fail "ночная выгрузка не прошла проверку длины записей"
echo "  длина записей сверена и на ночной дороге"

echo
echo "расписание сработало в срок и не раньше срока"
