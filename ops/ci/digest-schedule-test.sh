#!/usr/bin/env bash
# Расчёт времени до ночного свода: проверяется числами, а не ожиданием.
#
# Расписание — код, который выполняется раз в сутки. Ошибку в нём видно
# через сутки, а такую, что бьёт дважды в год, — через полгода. Поэтому
# точка входа умеет отвечать на вопрос «сколько ждать, если сейчас вот
# столько», и ответы сверяются здесь.
#
# ГЛАВНЫЙ СЛУЧАЙ — ПЕРЕХОД НА ЛЕТНЕЕ ВРЕМЯ. Один и тот же расчёт
# гоняется дважды: при TZ=UTC и при TZ=Europe/Berlin в ночь перевода
# стрелок. Ответ обязан СОВПАСТЬ. Уберите `-u` у `date` в точке входа —
# и берлинский случай разойдётся с utc-шным на час: свод уедет, и
# заметить это можно будет в последнее воскресенье марта.
set -uo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
ENTRY="$ROOT/ops/compose/digest-entrypoint.sh"

cd "$ROOT" || exit 1

rc=0

# `date` тут только для того, чтобы записать момент читаемо, а не
# числом эпохи: 1774832370 в тексте проверки ничего не объясняет.
epoch() { date -u -d "$1" +%s; }

сверить() {
  local title="$1" at="$2" moment="$3" want="$4" got now
  now="$(epoch "$moment")"
  got="$(bash "$ENTRY" next-in "$at" "$now" 2>&1)"
  if [ "$got" = "$want" ]; then
    echo "  $title: $got с"
  else
    echo "  $title: получено [$got], ждали [$want]" >&2
    rc=1
  fi
}

отвергнуть() {
  local title="$1" at="$2" out
  if out="$(bash "$ENTRY" next-in "$at" 1000000000 2>&1)"; then
    echo "  $title: принято «$at» и отвечено [$out]" >&2
    rc=1
  else
    echo "  $title: отвергнуто"
  fi
}

echo "==> сколько ждать до свода"
сверить "за полминуты до срока"  03:00 "2026-09-04T02:59:30Z"      30
сверить "ровно в срок: ждать сутки" 03:00 "2026-09-04T03:00:00Z" 86400
сверить "секундой позже"         03:00 "2026-09-04T03:00:01Z"   86399
сверить "через полночь"          00:30 "2026-09-04T23:59:00Z"     1860

echo
echo "==> перевод стрелок расчёту безразличен"
# Ночь на 29 марта 2026 года: в Берлине 02:00 местного превращается в
# 03:00, и суток в 86400 секунд в тот день там нет.
BERLIN_MOMENT="2026-03-29T00:30:00Z"
UTC_ANSWER="$(TZ=UTC bash "$ENTRY" next-in 03:00 "$(epoch "$BERLIN_MOMENT")")"
BERLIN_ANSWER="$(TZ=Europe/Berlin bash "$ENTRY" next-in 03:00 "$(epoch "$BERLIN_MOMENT")")"
if [ "$UTC_ANSWER" = "$BERLIN_ANSWER" ] && [ "$UTC_ANSWER" = "9000" ]; then
  echo "  в ночь перевода стрелок ответ тот же: $UTC_ANSWER с"
else
  echo "  расходятся: UTC [$UTC_ANSWER], Берлин [$BERLIN_ANSWER], ждали 9000" >&2
  rc=1
fi

echo
echo "==> расписание с опечаткой отвергается, а не толкуется"
отвергнуть "часа такого нет"        "25:00"
отвергнуть "минуты такой нет"       "03:75"
отвергнуть "без двоеточия"          "0300"
отвергнуть "одна цифра часа"        "3:00"
отвергнуть "слово вместо времени"   "ночью"
отвергнуть "пусто"                  ""

echo
if [ "$rc" -ne 0 ]; then
  echo "РАСПИСАНИЕ СЧИТАЕТ НЕ ТО" >&2
else
  echo "расписание считает верно и отвергает опечатки"
fi
exit "$rc"
