#!/usr/bin/env bash
# Проверка проверки длины записей: умеет ли она падать и на чём именно.
#
# Проверка, которая всегда зелёная, опаснее отсутствующей: она создаёт
# видимость. Здесь на вход подаются нарочно испорченные файлы, и каждый
# обязан быть отвергнут — причём СВОИМ сообщением, а не любым.
#
# ГЛАВНЫЙ СЛУЧАЙ — «короче и длиннее». Файл, где одна запись на байт
# короче, а другая на байт длиннее, имеет ПРАВИЛЬНЫЙ РАЗМЕР: 762 байта,
# как и положено двум записям. Дешёвая проверка делением размера на
# длину такой файл пропускает. Ловит его только тот, кто смотрит, где
# стоят переводы строк, — программа на Brainfuck.
#
# ОТДЕЛЬНО ИЗМЕРЯЕТСЯ КОНЕЦ ВХОДА. Что даёт чтение за концом файла,
# соглашением языка не определено: ноль, 255 или «оставить как было».
# Программа опирается на измеренное поведение этого интерпретатора, и
# подмена его на другой сменила бы смысл молча. Поэтому измеряется
# заново при каждом прогоне, а не записано в комментарий однажды.
set -uo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

cd "$ROOT" || exit 1

rc=0
fail() { echo "  ПРОВАЛ: $*" >&2; rc=1; }

LEN="$(awk '/^record_bytes:/ { print $2 }' contracts/reports/digest-v1.yaml)"
[ -n "$LEN" ] || { echo "нет record_bytes в контракте" >&2; exit 1; }

FINGERPRINT="$(sha1sum report/src/reclen.bf | cut -c1-12)"
IMAGE="sonder/reclen:$FINGERPRINT"

echo "==> образ проверки ($IMAGE)"
if docker image inspect "$IMAGE" > /dev/null 2>&1; then
  echo "  уже собран"
else
  docker build -q -f ops/compose/Dockerfile.bf -t "$IMAGE" . > /dev/null \
    || { echo "не собрать образ" >&2; exit 1; }
  echo "  собран"
fi

# --- Чем кончается вход ------------------------------------------------
#
# Печатается буква, затем читается байт за концом входа, затем печать
# снова. Если интерпретатор кладёт в ячейку значение и продолжает — букв
# будет две. Измерено: буква одна, программа прекращается.
echo
echo "==> поведение интерпретатора на конце входа"
EOFOUT="$(docker run --rm -i --entrypoint sh "$IMAGE" -c '
  printf "++++++++++[>++++++++++<-]>+++++.,." > /tmp/probe.bf
  beef /tmp/probe.bf < /dev/null | od -An -tu1 | tr -s " "
')"
EOFCODE=$?
if [ "$EOFCODE" -ne 0 ]; then
  fail "проба конца входа не отработала"
elif [ "$(echo "$EOFOUT" | tr -d ' \n')" = "105" ]; then
  echo "  чтение за концом входа прекращает программу — как и заложено"
else
  fail "интерпретатор ведёт себя иначе: [$EOFOUT] вместо [105].
    Программа рассчитана на прекращение; при другом соглашении она
    зациклится на сбитом выравнивании."
fi

# --- Приготовление входов ---------------------------------------------
запись() { head -c "$1" < /dev/zero | tr '\0' 'a'; }

{ запись "$LEN"; printf '\n'; запись "$LEN"; printf '\n'; } > "$WORK/good.dat"
{ запись "$((LEN - 1))"; printf '\n'; запись "$((LEN + 1))"; printf '\n'; } \
  > "$WORK/skew.dat"
{ запись "$((LEN - 1))"; printf '\n'; } > "$WORK/short.dat"
: > "$WORK/empty.dat"
{ запись "$LEN"; printf '\n'; head -c "$LEN" < /dev/zero; printf '\n';
  запись "$LEN"; printf '\n'; } > "$WORK/hole.dat"

# --- Случаи ------------------------------------------------------------
годен() {
  local title="$1" file="$2" out
  echo
  echo "==> $title"
  if out="$(bash ops/ci/reclen.sh "$file" 2>&1)"; then
    echo "$out" | sed 's/^/  /'
  else
    echo "$out" | sed 's/^/    /' >&2
    fail "исправный файл отвергнут"
  fi
}

негоден() {
  local title="$1" file="$2" want="$3" out
  echo
  echo "==> $title"
  if out="$(bash ops/ci/reclen.sh "$file" 2>&1)"; then
    echo "$out" | sed 's/^/    /' >&2
    fail "испорченный файл принят"
  # Здесь строка подаётся grep-у ПОДСТРОКОЙ, а не через канал: `grep -q`
  # закрывает канал на первом совпадении, пишущий получает SIGPIPE, и при
  # `pipefail` успешное совпадение возвращает ненулевой код. Этот капкан
  # уже один раз объявил провалившейся исправную проверку.
  elif grep -qa -- "$want" <<< "$out"; then
    echo "  отвергнут по делу: $(grep -a -m1 -- "$want" <<< "$out")"
  else
    echo "$out" | sed 's/^/    /' >&2
    fail "отвергнут, но не по делу: ждали «$want»"
  fi
}

годен   "две верные записи" "$WORK/good.dat"
годен   "пустой файл: записей ноль, и это ответ" "$WORK/empty.dat"

# Размер правильный, записи — нет. Ради этого случая проверка и написана.
негоден "одна короче, другая длиннее — размер файла верен" \
        "$WORK/skew.dat" "записей не той длины"

негоден "одна запись, короче на байт" \
        "$WORK/short.dat" "не делится"

# Запись из одних нулей — признак конца, и в середине файла она означает,
# что файл не тот, за кого себя выдаёт. Программа остановится на ней, и
# отметок окажется меньше, чем записей.
негоден "запись из одних нулей в середине файла" \
        "$WORK/hole.dat" "не дошла до конца файла"

echo
if [ "$rc" -ne 0 ]; then
  echo "ПРОВЕРКА ДЛИНЫ ЗАПИСЕЙ НЕНАДЁЖНА" >&2
else
  echo "проверка длины ловит перекос, обрыв и подмену; исправное пропускает"
fi
exit "$rc"
