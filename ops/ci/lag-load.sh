#!/usr/bin/env bash
# Лаг read-model ПОД НАГРУЗКОЙ.
#
# `./sonder lag` меряет спокойную систему и даёт p99 около 935 мс при
# цели в секунду — запас шесть процентов. Но SLO обещан не для тишины:
# под нагрузкой дренаж конкурирует за базу с самой записью, а событий
# на разбор становится столько, сколько команд приняла система.
#
# ЧТО ЗДЕСЬ МОЖЕТ СЛОМАТЬСЯ. Потолок записи — 21,5 команды/с; дренаж
# измерен на 82–127 событий/с. Запас четырёхкратный, и если он честный,
# лаг под нагрузкой вырастет незначительно. Если же дренаж и запись
# мешают друг другу в базе, лаг поедет — и SLO, взятый в тишине,
# окажется взятым не там.
#
# КАК МЕРЯЕТСЯ. Поднимается запись на уровне колена (4 потока), ей даётся
# время выйти на режим, и поверх идёт обычный замер лага. Нагрузка живёт
# в своём контейнере и снимается по окончании — в том числе при
# прерывании.
set -uo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
NET="${SONDER_E2E_NET:-sonder_default}"
INNER_URL="${SONDER_INNER_URL:-https://web:443}"

# Потоки записи. Четыре — колено: дальше система начинает отказывать, и
# мерился бы лаг на фоне отказов, а не под нагрузкой.
THREADS="${SONDER_LAGLOAD_THREADS:-4}"

# Сколько держать нагрузку. Должно с запасом перекрыть замер лага:
# пятнадцать постов по секунде плюс подготовка.
LOAD_SECONDS="${SONDER_LAGLOAD_SECONDS:-90}"

# Пишущих под нагрузку. Домен разрешает 20 постов в час на человека, и
# при 21 команде/с за полторы минуты уходит около двух тысяч — то есть
# нужно не меньше сотни, иначе замер упрётся в квоту и станет мерить
# скорость отказов.
LOAD_USERS="${SONDER_LAGLOAD_USERS:-160}"

NAME=sonder-lagload

cd "$ROOT" || exit 1

stop_load() {
  docker rm -f "$NAME" > /dev/null 2>&1 || true
}
trap stop_load EXIT

if ! docker network inspect "$NET" > /dev/null 2>&1; then
  echo "нет сети $NET — система не поднята. Сначала ./sonder up" >&2
  exit 1
fi

echo "==> лаг read-model под нагрузкой"
echo "  потоков записи: $THREADS, пишущих: $LOAD_USERS, держим ${LOAD_SECONDS} с"

stop_load
docker run -d --name "$NAME" \
  --network "$NET" \
  -v "$ROOT/ops/bench:/bench:ro" \
  -w /bench \
  python:3.12-alpine \
  python -u load.py \
    --url "$INNER_URL" \
    --users "$LOAD_USERS" \
    --seconds "$LOAD_SECONDS" \
    --levels "$THREADS" \
    --mode write > /dev/null

# `-u` выше ОБЯЗАТЕЛЕН, и это не мелочь удобства. Python буферизует
# вывод блоками, когда тот не в терминал, и строка готовности осталась бы
# в буфере: ожидание ниже не выполнилось бы никогда, а скрипт доложил бы
# «нагрузка не вышла на режим за 120 с» об исправной нагрузке. Ровно так
# и случилось при первом прогоне.
echo "  ждём выхода нагрузки на режим…"
# Подготовка нагрузки — это регистрация сотни с лишним пишущих, и она
# сама по себе идёт через ядро. Ждём, пока в выводе появится строка о
# готовности: спать «примерно столько» значило бы мерить то подготовку,
# то нагрузку, по-разному от прогона к прогону.
ready=0
for _ in $(seq 1 120); do
  if docker logs "$NAME" 2>&1 | grep -aq "готово:"; then
    ready=1
    break
  fi
  if ! docker ps --filter "name=$NAME" --format '{{.Names}}' | grep -q "$NAME"; then
    echo "  нагрузка не поднялась:" >&2
    docker logs "$NAME" 2>&1 | tail -5 >&2
    exit 1
  fi
  sleep 1
done
if [ "$ready" -ne 1 ]; then
  # Журнал берётся ДО того, как ловушка снимет контейнер: при первом
  # провале он исчез вместе с ним, и разбираться было не с чем.
  echo "  нагрузка не вышла на режим за 120 с. Её вывод:" >&2
  docker logs "$NAME" 2>&1 | tail -8 >&2 || echo "  журнала нет" >&2
  exit 1
fi

echo "  нагрузка на режиме, меряем лаг"
echo

bash ops/ci/lag.sh
rc=$?

echo
echo "==> что делала нагрузка в это время"
docker logs "$NAME" 2>&1 | grep -aE "^ *[0-9]+ " | tail -3 | sed 's/^/  /'

exit "$rc"
