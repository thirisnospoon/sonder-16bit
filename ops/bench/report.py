"""
Графики насыщения и сводка замера.

СВОЙ SVG, а не библиотека построения графиков. Причина та же, по которой
у фронта нет фреймворка: график здесь — это оси, ломаная и подписи, и
тянуть ради них matplotlib с половиной научного стека значило бы завести
зависимость размером больше самого проекта. Формат при этом текстовый и
ложится в версию рядом с числами, из которых построен.

Фон рисуется ЯВНО. Прозрачный SVG выглядит прилично ровно до первого
просмотра в тёмной теме, где чёрные подписи оказываются на чёрном; на
графике, вложенном в документ, это не мелочь, а нечитаемый график.
"""
import json
import sys
from pathlib import Path

Ш, В = 760, 340
ПОЛЯ = {"слева": 74, "справа": 26, "сверху": 46, "снизу": 56}

ФОН = "#fbfbfd"
СЕТКА = "#dfe1e8"
ОСЬ = "#3c4048"
ТЕКСТ = "#22252b"
ТУСКЛЫЙ = "#666b75"
ЛИНИИ = ["#3f5fd0", "#c0392b", "#1f8a5f", "#8e44ad"]
ШРИФТ = "system-ui, -apple-system, 'Segoe UI', Roboto, sans-serif"


def экранировать(s: str) -> str:
    return (s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"))


class Холст:
    def __init__(self, заголовок: str, подзаголовок: str) -> None:
        self.куски: list[str] = []
        self.заголовок = заголовок
        self.подзаголовок = подзаголовок

    def прямая(self, x1, y1, x2, y2, цвет, толщина=1.0, пунктир=None) -> None:
        d = f' stroke-dasharray="{пунктир}"' if пунктир else ""
        self.куски.append(
            f'<line x1="{x1:.1f}" y1="{y1:.1f}" x2="{x2:.1f}" y2="{y2:.1f}" '
            f'stroke="{цвет}" stroke-width="{толщина}"{d}/>'
        )

    def ломаная(self, точки, цвет) -> None:
        d = " ".join(f"{x:.1f},{y:.1f}" for x, y in точки)
        self.куски.append(
            f'<polyline points="{d}" fill="none" stroke="{цвет}" '
            f'stroke-width="2.2" stroke-linejoin="round" stroke-linecap="round"/>'
        )
        for x, y in точки:
            self.куски.append(
                f'<circle cx="{x:.1f}" cy="{y:.1f}" r="3.4" fill="{цвет}"/>'
            )

    def надпись(self, x, y, текст, цвет=ТЕКСТ, размер=12, якорь="middle",
                вес="400") -> None:
        self.куски.append(
            f'<text x="{x:.1f}" y="{y:.1f}" fill="{цвет}" font-size="{размер}" '
            f'font-family="{ШРИФТ}" font-weight="{вес}" '
            f'text-anchor="{якорь}">{экранировать(текст)}</text>'
        )

    def собрать(self) -> str:
        шапка = [
            f'<svg xmlns="http://www.w3.org/2000/svg" width="{Ш}" height="{В}" '
            f'viewBox="0 0 {Ш} {В}" role="img" '
            f'aria-label="{экранировать(self.заголовок)}">',
            f'<rect width="{Ш}" height="{В}" fill="{ФОН}"/>',
        ]
        подписи = [
            f'<text x="{ПОЛЯ["слева"]}" y="24" fill="{ТЕКСТ}" font-size="15" '
            f'font-family="{ШРИФТ}" font-weight="600">'
            f'{экранировать(self.заголовок)}</text>',
            f'<text x="{ПОЛЯ["слева"]}" y="40" fill="{ТУСКЛЫЙ}" font-size="11.5" '
            f'font-family="{ШРИФТ}">{экранировать(self.подзаголовок)}</text>',
        ]
        return "\n".join(шапка + подписи + self.куски + ["</svg>"]) + "\n"


def логарифм(значение: float, низ: float, верх: float) -> float:
    """Доля высоты для логарифмической шкалы.

    Нужна там, где на одном поле встречаются величины, различающиеся на
    порядок: линейная шкала прижимает меньшую к нулю, и её форма — а
    именно форма и есть насыщение — становится неразличимой. Ноль на
    логарифмической шкале не изображается, поэтому он поднимается к
    нижней границе, а не выбрасывается молча.
    """
    import math
    if значение <= низ:
        return 0.0
    return (math.log10(значение) - math.log10(низ)) / (
        math.log10(верх) - math.log10(низ))


def оси(холст: Холст, подписи_x: list[str], верх: float, подпись_y: str,
        деления: int = 5) -> tuple:
    x0 = ПОЛЯ["слева"]
    x1 = Ш - ПОЛЯ["справа"]
    y0 = В - ПОЛЯ["снизу"]
    y1 = ПОЛЯ["сверху"]

    for i in range(деления + 1):
        y = y0 + (y1 - y0) * i / деления
        холст.прямая(x0, y, x1, y, СЕТКА, 1.0, "3 4" if i else None)
        холст.надпись(x0 - 10, y + 4, f"{верх * i / деления:g}", ТУСКЛЫЙ, 11, "end")

    холст.прямая(x0, y0, x1, y0, ОСЬ, 1.4)
    холст.прямая(x0, y0, x0, y1, ОСЬ, 1.4)

    шаг = (x1 - x0) / max(1, len(подписи_x) - 1)
    for i, п in enumerate(подписи_x):
        x = x0 + шаг * i
        холст.надпись(x, y0 + 20, п, ТУСКЛЫЙ, 11)
    холст.надпись((x0 + x1) / 2, В - 14, "потоков одновременно", ТУСКЛЫЙ, 11.5)
    холст.куски.append(
        f'<text x="18" y="{(y0 + y1) / 2:.1f}" fill="{ТУСКЛЫЙ}" font-size="11.5" '
        f'font-family="{ШРИФТ}" text-anchor="middle" '
        f'transform="rotate(-90 18 {(y0 + y1) / 2:.1f})">'
        f'{экранировать(подпись_y)}</text>'
    )
    return x0, x1, y0, y1, шаг


def легенда(холст: Холст, имена: list[str]) -> None:
    x = Ш - ПОЛЯ["справа"]
    for i, имя in enumerate(reversed(имена)):
        цвет = ЛИНИИ[len(имена) - 1 - i]
        # На строке ЗАГОЛОВКА. Между заголовком и подзаголовком легенда
        # налезала на подзаголовок, стоило тому оказаться длинным.
        y = 24
        ширина = 8 + len(имя) * 6.4
        x -= ширина + 16
        холст.куски.append(
            f'<rect x="{x:.1f}" y="{y - 8:.1f}" width="10" height="10" rx="2" '
            f'fill="{цвет}"/>'
        )
        холст.надпись(x + 15, y + 1, имя, ТУСКЛЫЙ, 11.5, "start")


def верхняя_граница(значения: list[float]) -> float:
    предел = max(значения + [1e-9])
    шаг = 10 ** (len(str(int(предел))) - 1) if предел >= 1 else 0.1
    while шаг * 5 > предел:
        шаг /= 2
    return (int(предел / шаг) + 1) * шаг


def оси_лог(холст: Холст, подписи_x: list[str], низ: float, верх: float,
            подпись_y: str) -> tuple:
    import math
    x0 = ПОЛЯ["слева"]
    x1 = Ш - ПОЛЯ["справа"]
    y0 = В - ПОЛЯ["снизу"]
    y1 = ПОЛЯ["сверху"]

    метки = []
    степень = int(math.floor(math.log10(низ)))
    while 10 ** степень <= верх:
        for m in (1, 3):
            v = m * 10 ** степень
            if низ <= v <= верх:
                метки.append(v)
        степень += 1
    if верх not in метки:
        метки.append(верх)

    # Слишком близкие подписи не рисуются: на логарифмической шкале
    # верхняя граница легко оказывается рядом с последним делением, и
    # две надписи налезают друг на друга, превращаясь в кашу.
    занято: list[float] = []
    for v in метки:
        y = y0 + (y1 - y0) * логарифм(v, низ, верх)
        холст.прямая(x0, y, x1, y, СЕТКА, 1.0, "3 4")
        if all(abs(y - было) >= 12 for было in занято):
            холст.надпись(x0 - 10, y + 4, f"{v:g}", ТУСКЛЫЙ, 11, "end")
            занято.append(y)

    холст.прямая(x0, y0, x1, y0, ОСЬ, 1.4)
    холст.прямая(x0, y0, x0, y1, ОСЬ, 1.4)

    шаг = (x1 - x0) / max(1, len(подписи_x) - 1)
    for i, п in enumerate(подписи_x):
        холст.надпись(x0 + шаг * i, y0 + 20, п, ТУСКЛЫЙ, 11)
    холст.надпись((x0 + x1) / 2, В - 14, "потоков одновременно", ТУСКЛЫЙ, 11.5)
    холст.куски.append(
        f'<text x="18" y="{(y0 + y1) / 2:.1f}" fill="{ТУСКЛЫЙ}" font-size="11.5" '
        f'font-family="{ШРИФТ}" text-anchor="middle" '
        f'transform="rotate(-90 18 {(y0 + y1) / 2:.1f})">'
        f'{экранировать(подпись_y)}</text>'
    )
    return x0, x1, y0, y1, шаг


def график(путь: Path, заголовок: str, подзаголовок: str, подписи_x: list[str],
           ряды: list[tuple[str, list[float]]], подпись_y: str,
           лог: bool = False) -> None:
    холст = Холст(заголовок, подзаголовок)
    все = [v for _, ряд in ряды for v in ряд]
    if лог:
        низ = max(1.0, min(v for v in все if v > 0) / 2)
        верх = верхняя_граница(все)
        x0, x1, y0, y1, шаг = оси_лог(холст, подписи_x, низ, верх, подпись_y)
        доля = lambda v: логарифм(v, низ, верх)  # noqa: E731
    else:
        верх = верхняя_граница(все)
        x0, x1, y0, y1, шаг = оси(холст, подписи_x, верх, подпись_y)
        доля = lambda v: (v / верх if верх else 0)  # noqa: E731
    for i, (_, ряд) in enumerate(ряды):
        точки = [
            (x0 + шаг * j, y0 + (y1 - y0) * доля(v))
            for j, v in enumerate(ряд)
        ]
        холст.ломаная(точки, ЛИНИИ[i % len(ЛИНИИ)])
    легенда(холст, [имя for имя, _ in ряды])
    путь.write_text(холст.собрать(), encoding="utf-8")
    print(f"  {путь}")


def таблица(строки: list[dict]) -> str:
    из = ["| потоков | запросов | успешно | 429 | отказов | зпс | p50, мс | p95, мс | p99, мс |",
          "|--------:|---------:|--------:|----:|--------:|----:|--------:|--------:|--------:|"]
    for s in строки:
        из.append(
            f"| {s['concurrency']} | {s['requests']} | {s['ok']} | "
            f"{s['rate_limited']} | {s['failed']} | {s['rps']:.2f} | "
            f"{s['p50_ms']:.0f} | {s['p95_ms']:.0f} | {s['p99_ms']:.0f} |"
        )
    return "\n".join(из)


def main() -> int:
    if len(sys.argv) != 4:
        print("нужно: report.py <write.json> <read.json> <куда>", file=sys.stderr)
        return 2
    запись = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
    чтение = json.loads(Path(sys.argv[2]).read_text(encoding="utf-8"))
    куда = Path(sys.argv[3])

    подписи = [str(s["concurrency"]) for s in запись]

    график(
        куда / "throughput.svg",
        "Пропускная способность: запись против чтения",
        "Шкала логарифмическая: на линейной запись прижимается к нулю чтением.",
        подписи,
        [("запись", [s["rps"] for s in запись]),
         ("чтение", [s["rps"] for s in чтение])],
        "успешных запросов в секунду",
        лог=True,
    )

    # ТОЛЬКО пропускная способность, в своём масштабе. Класть на то же
    # поле число отказов пробовали: их тысячи против двух десятков
    # запросов в секунду, и линия отдачи снова становилась прямой у нуля
    # — той самой, ради разглядывания которой график и заводился. Что
    # происходит за коленом, рассказывают задержки и таблица.
    график(
        куда / "throughput-write.svg",
        "Насыщение записи",
        "Свой масштаб: колено видно только здесь.",
        подписи,
        [("успешных в секунду", [s["rps"] for s in запись])],
        "команд в секунду",
    )

    график(
        куда / "latency-write.svg",
        "Задержка записи под нагрузкой",
        "Очередь к линии: команды ждут своей очереди на круговой обмен.",
        подписи,
        [("p50", [s["p50_ms"] for s in запись]),
         ("p95", [s["p95_ms"] for s in запись]),
         ("p99", [s["p99_ms"] for s in запись])],
        "миллисекунд",
    )

    график(
        куда / "latency-read.svg",
        "Задержка чтения под нагрузкой",
        "Линию не трогает: проекция читается из базы.",
        подписи,
        [("p50", [s["p50_ms"] for s in чтение]),
         ("p95", [s["p95_ms"] for s in чтение]),
         ("p99", [s["p99_ms"] for s in чтение])],
        "миллисекунд",
    )

    # ПОТОЛОК — это не пик числа, а последний уровень, на котором система
    # ещё держит слово. Уровень с отказами показывает пропускную
    # способность больше именно потому, что часть работы выбрасывает:
    # объявить его потолком значило бы записать в достижения скорость, с
    # которой система говорит «нет».
    чистые = [s for s in запись if s["failed"] == 0 and s["rate_limited"] == 0]
    на_потолке = max(чистые or запись, key=lambda s: s["rps"])
    потолок = на_потолке["rps"]

    # Где начинается насыщение: пропускная способность дальше не растёт,
    # а задержка упирается в предел ожидания ядра.
    насыщение = next((s for s in запись if s["failed"] > 0), None)

    чистые_чтение = [s for s in чтение if s["failed"] == 0]
    на_чтении = max(чистые_чтение or чтение, key=lambda s: s["rps"])
    чтение_макс = на_чтении["rps"]

    сводка = куда / "SUMMARY.md"
    сводка.write_text(
        f"# Числа замера\n\n"
        f"Порождено `ops/bench/report.py`. Правится замером, а не руками.\n\n"
        f"## Запись\n\n{таблица(запись)}\n\n"
        f"## Чтение\n\n{таблица(чтение)}\n\n"
        f"## Итог\n\n"
        f"- потолок записи БЕЗ ОТКАЗОВ: **{потолок:.2f} команд/с** "
        f"(при {на_потолке['concurrency']} потоках, p50 "
        f"{на_потолке['p50_ms']:.0f} мс, p95 {на_потолке['p95_ms']:.0f} мс)\n"
        + (f"- насыщение с {насыщение['concurrency']} потоков: "
           f"{насыщение['failed']} отказов, p99 {насыщение['p99_ms']:.0f} мс\n"
           if насыщение else "- отказов не было ни на одном уровне\n")
        + f"- потолок чтения: **{чтение_макс:.2f} запросов/с** "
        f"(при {на_чтении['concurrency']} потоках, p95 "
        f"{на_чтении['p95_ms']:.0f} мс)\n"
        f"- отношение чтения к записи: **×{чтение_макс / потолок:.0f}**\n",
        encoding="utf-8",
    )
    print(f"  {сводка}")
    print()
    print(f"потолок записи без отказов: {потолок:.2f} команд/с "
          f"при {на_потолке['concurrency']} потоках")
    print(f"потолок чтения: {чтение_макс:.2f} запросов/с")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
