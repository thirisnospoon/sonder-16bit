#!/usr/bin/env python3
"""
Самопроверка сборщика Brainfuck.

Сборщик существует ради своих запретов (см. gen_reclen.py). Запрет, который
ни разу не сработал, неотличим от отсутствующего: первая редакция файла
носила пометки об указателе, расставленные руками, и они врали — потому
пометки и стали вычисляемыми.

Здесь сборщику по одному подсовываются ровно те ошибки, от которых он
поставлен, и проверяется, что он падает и говорит по делу.

Выход: 0 — ловит всё, 1 — что-то пропускает.
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path


def загрузить():
    """Импорт генератора по пути: каталог с дефисом пакетом не назвать."""
    # Байткод не писать: импорт ради проверки не должен оставлять в
    # дереве файлов, которых там не ждут.
    sys.dont_write_bytecode = True
    путь = Path(__file__).parent / "gen_reclen.py"
    спец = importlib.util.spec_from_file_location("gen_reclen", путь)
    модуль = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(модуль)
    return модуль


def ждать_отказа(имя: str, действие, кусок: str) -> bool:
    """Действие обязано упасть, и в жалобе обязан быть указанный кусок."""
    try:
        действие()
    except SystemExit as e:
        текст = str(e)
        if кусок in текст:
            print("  {}: пойман — {}".format(имя, текст.split(":")[0]))
            return True
        print("  {}: упал, но не по делу — {}".format(имя, текст),
              file=sys.stderr)
        return False
    except Exception as e:  # noqa: BLE001 — падение не тем способом тоже беда
        print("  {}: упал не тем способом — {!r}".format(имя, e),
              file=sys.stderr)
        return False
    print("  {}: ПРОПУЩЕН".format(имя), file=sys.stderr)
    return False


def main() -> int:
    ген = загрузить()
    беды = 0

    # 1. Цикл, оставляющий указатель не там, где взял. Программа с таким
    #    циклом работает и печатает правдоподобное — со второго прохода
    #    трогая соседнюю ячейку.
    def смещённый_цикл():
        п = ген.Сборщик()
        п.код("[", "цикл")
        п.код(">", "ушли вправо и не вернулись")
        п.код("]", "закрыли")

    беды += not ждать_отказа("смещение внутри цикла", смещённый_цикл,
                             "смещение внутри тела не ноль")

    # 2. Пояснение с командой. В этом языке комментариев нет: точка в
    #    тексте печатает байт, минус меняет ячейку.
    def болтливое_пояснение():
        п = ген.Сборщик()
        п.код("+", "единица, и точка.")

    беды += not ждать_отказа("команда в пояснении", болтливое_пояснение,
                             "есть команды")

    # 3. Выход за объявленную разметку: ячейка, которой нет в таблице,
    #    это либо чужая память, либо чужой смысл.
    def за_разметкой():
        п = ген.Сборщик()
        п.код("<", "влево от нулевой")

    беды += not ждать_отказа("указатель за разметкой", за_разметкой,
                             "указатель ушёл в ячейку")

    # 4. Незакрытая скобка: интерпретатор такое просто не запустит, но
    #    сказать об этом обязан генератор, а не он.
    def незакрытая():
        п = ген.Сборщик()
        п.код("[", "открыли и забыли")
        п.готово()

    беды += not ждать_отказа("незакрытая скобка", незакрытая,
                             "незакрытых скобок")

    # 5. Программа, кончившаяся не в нулевой ячейке: следующий проход
    #    внешнего цикла начался бы со сдвинутой разметкой.
    def кончилась_не_там():
        п = ген.Сборщик()
        п.код(">", "ушли и остались")
        п.готово()

    беды += not ждать_отказа("конец не в нулевой ячейке", кончилась_не_там,
                             "а не в нулевой")

    # 6. Серия плюсов длиннее ёмкости ячейки. Числа больше 255 в ячейку
    #    не кладутся, а сворачиваются: 379 становится 123, и программа
    #    читает записи по 125 байт вместо 380, ни на что не жалуясь.
    #    Ровно так и вышло при первой сборке быстрой редакции — поймано
    #    по семи отметкам там, где ждали две.
    def переполнение_ячейки():
        п = ген.Сборщик()
        п.число("inner", 379, "байт за проход")

    беды += not ждать_отказа("серия плюсов длиннее ячейки",
                             переполнение_ячейки, "она держит от 1 до 255")

    # Проверка, что сборщик вообще пропускает исправное: иначе он мог бы
    # падать на всём подряд и все случаи прошли бы даром.
    п = ген.Сборщик()
    п.код("+", "единица")
    п.код("[", "цикл")
    п.к("t1", "к временной")
    п.код("[-]", "обнулить")
    п.к("go", "обратно")
    п.код("-", "к нулю")
    п.код("]", "конец")
    текст = п.готово()
    if "[-]" not in текст:
        print("  исправная программа не собралась", file=sys.stderr)
        беды += 1
    else:
        print("  исправное собирается: строк {}".format(
            len(текст.splitlines())))

    if беды:
        print("сборщик пропускает дефекты: {}".format(беды), file=sys.stderr)
        return 1
    print("сборщик ловит все шесть дефектов и собирает исправное")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
