def разметка_ленты() -> str:
    подписи = {
        "go": "идёт ли обработка",
        "outer": "внешний счётчик длины",
        "inner": "внутренний счётчик длины",
        "b": "прочитанный байт",
        "t1": "временная",
        "t2": "временная",
        "err": "в записи что то не так",
        "seen": "был хоть один ненулевой байт",
        "out": "собираемый для печати символ",
        "t3": "временная для ветвления по err",
    }
    return "\n".join("  {:<3} {:<7} {}".format(номер, имя, подписи[имя])
                     for имя, номер in ЯЧЕЙКИ.items())


def собрать(длина: int) -> str:
    внешний, внутренний = разложить(длина)
    п = Сборщик()

    п.код("+", "обработка идёт")
    п.код("[", "пока идёт")

    п.пусто()
    п.речь("  начало записи: вся рабочая часть ленты чистая")
    for имя in ЯЧЕЙКИ:
        if имя == "go":
            continue
        п.к(имя, "очистка")
        п.код("[-]", "обнулить")
    п.к("go", "к началу разметки")

    п.пусто()
    п.речь("  прочитать ровно {} байт".format(длина))
    п.к("outer", "внешний счётчик")
    п.число("outer", внешний, "внешних проходов")
    п.код("[", "внешний цикл")
    п.к("inner", "внутренний счётчик")
    п.число("inner", внутренний, "байт за проход")
    п.код("[", "внутренний цикл")

    п.к("b", "читаем байт")
    п.код(",", "байт с входа")
    п.код("[-" + сдв("b", "t1") + "+" + сдв("t1", "t2") + "+"
          + сдв("t2", "b") + "]", "копия байта в две временные")
    п.к("t2", "вторая копия")
    п.код("[-" + сдв("t2", "b") + "+" + сдв("b", "t2") + "]",
          "вернуть байт на место")
    п.к("t1", "первая копия")
    п.код("[[-]" + сдв("t1", "seen") + "[-]+" + сдв("seen", "t1") + "]",
          "байт не ноль значит запись не пустая")

    п.к("b", "к байту")
