def сдв(откуда: str, куда: str) -> str:
    """Ход указателя между двумя названными ячейками.

    Нужен там, где ход стоит ВНУТРИ готового оборота и не может быть
    отдельной строкой. Написанное руками число стрелок пережило бы любую
    перестановку разметки молча: программа продолжила бы работать, просто
    трогая не ту ячейку.
    """
    шаг = ЯЧЕЙКИ[куда] - ЯЧЕЙКИ[откуда]
    return (">" if шаг > 0 else "<") * abs(шаг)


class Сборщик:
    """Пишет Brainfuck и следит за тем, за чем человек не уследил.

    Что именно проверяется на лету:

      * КАЖДЫЙ ЦИКЛ ВОЗВРАЩАЕТ УКАЗАТЕЛЬ. В этом языке `[тело]` выполняет
        тело неизвестное число раз, поэтому смещение указателя внутри
        тела обязано быть нулевым — иначе после второго прохода вся
        разметка ленты означает не то. Ошибка молчаливая: программа
        работает и печатает правдоподобное.

      * УКАЗАТЕЛЬ НЕ УХОДИТ ЗА РАЗМЕТКУ. Ячейка за пределами объявленных
        — это либо чужая память, либо чужой смысл.

      * ПОЯСНЕНИЯ НЕ СОДЕРЖАТ КОМАНД. Любой из символов + - < > [ ] , .
        внутри пояснения ЕСТЬ КОМАНДА: комментариев в языке нет, есть
        только «остальные символы игнорируются». Пояснение с точкой
        печатает байт.
    """

    def __init__(self) -> None:
        self.строки: list[str] = []
        self.указатель = 0
        self.стек: list[tuple[int, int]] = []

    # --- проверки ---------------------------------------------------

    @staticmethod
    def _без_команд(текст: str, где: str) -> None:
        плохие = sorted({c for c in текст if c in КОМАНДЫ})
        if плохие:
            raise SystemExit(
                "в пояснении «{}» есть команды {}: {}"
                .format(текст, "".join(плохие), где))

    # --- письмо -----------------------------------------------------

    def пусто(self) -> None:
        self.строки.append("")

    def речь(self, текст: str) -> None:
        """Строка пояснения без кода."""
        self._без_команд(текст, "текст между кусками")
        self.строки.append(текст)

    def код(self, куски: str, пояснение: str) -> None:
        self._без_команд(пояснение, "рядом с кодом " + куски)
        глубина_до = len(self.стек)
        for c in куски:
            if c == ">":
                self.указатель += 1
            elif c == "<":
                self.указатель -= 1
            elif c == "[":
                self.стек.append((self.указатель, len(self.строки)))
            elif c == "]":
                if not self.стек:
                    raise SystemExit("лишняя закрывающая скобка")
                начало, строка = self.стек.pop()
                if начало != self.указатель:
                    raise SystemExit(
                        "цикл, начатый на строке {} в ячейке {}, "
                        "закрыт в ячейке {}: смещение внутри тела не ноль"
                        .format(строка + 1, начало, self.указатель))
            if not 0 <= self.указатель < len(ЯЧЕЙКИ):
                raise SystemExit(
                    "указатель ушёл в ячейку {} при разметке на {}: {}"
                    .format(self.указатель, len(ЯЧЕЙКИ), пояснение))
        отступ = "  " * min(глубина_до, len(self.стек))
        левое = отступ + куски
        # Разрыв обязателен, даже когда код шире колонки: серия из сорока
        # шести плюсов, упершаяся в слово «out», читается как одно слово,
        # а считать плюсы глазами тут и так не выйдет.
        зазор = " " * max(2, 44 - len(левое))
        self.строки.append("{}{}{}  ячейка {}"
                           .format(левое, зазор, пояснение, self.указатель))

    def к(self, имя: str, пояснение: str) -> None:
        """Перевести указатель в названную ячейку."""
        цель = ЯЧЕЙКИ[имя]
        шаг = цель - self.указатель
        if шаг == 0:
            return
        self.код((">" if шаг > 0 else "<") * abs(шаг),
                 "к ячейке {}: {}".format(имя, пояснение))

    def число(self, имя: str, сколько: int, пояснение: str) -> None:
        """Прибавить к текущей ячейке столько единиц, сколько сказано."""
        self.код("+" * сколько, "{} равно {}: {}".format(имя, сколько,
                                                         пояснение))

    def готово(self) -> str:
        if self.стек:
            raise SystemExit("незакрытых скобок: {}".format(len(self.стек)))
        if self.указатель != 0:
            raise SystemExit(
                "программа кончилась в ячейке {}, а не в нулевой"
                .format(self.указатель))
        return "\n".join(self.строки) + "\n"


def разложить(n: int) -> tuple[int, int]:
    """Разложить длину записи на два множителя, поближе друг к другу.

    Счётчик в этом языке — серия плюсов, поэтому 380 плюсов подряд можно
    заменить вложенными циклами 19 на 20 и написать 39 знаков вместо 380.
    Простое число раскладывается как единица на само себя: длинно, но
    верно, а верность тут важнее.
    """
    лучшее = (1, n)
    for a in range(2, int(n ** 0.5) + 1):
        if n % a == 0:
            лучшее = (a, n // a)
    return лучшее


