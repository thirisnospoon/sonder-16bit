def разметка_ленты() -> str:
    подписи = {
        "go": "идёт ли обработка",
        "outer": "внешний счётчик длины",
        "inner": "внутренний счётчик длины",
        "b": "прочитанный байт",
        "t1": "временная",
        "t2": "временная",
        "err": "в записи что то не так",
        "seen": "первый байт записи не ноль",
        "out": "собираемый для печати символ",
        "t3": "временная для ветвления по err",
        "t4": "временная для ветвления по seen",
    }
    return "\n".join("  {:<3} {:<7} {}".format(номер, имя, подписи[имя])
                     for имя, номер in ЯЧЕЙКИ.items())


def собрать(длина: int) -> str:
    """Собрать программу.

    ЧТО ИМЕННО СЧИТАЕТ ЭТА ПРОГРАММА — положение перевода строки, а не
    значения байтов. Вопрос к каждой записи один: стоит ли перевод строки
    на 381-м байте от её начала. Это и есть определение файла
    фиксированной ширины, и считается оно в БАЙТАХ — единственное, что
    Brainfuck умеет считать.

    ЗНАЧЕНИЯ ОСТАЛЬНЫХ БАЙТОВ НЕ СМОТРЯТСЯ, и это решение по замеру, а не
    по вкусу.

    Всякая работа с байтом в этом языке стоит столько шагов, каково его
    ЗНАЧЕНИЕ: и копия, и обнуление — циклы, крутящиеся `значение` раз.
    Три редакции подряд платили эту цену на каждом байте:

      * с копией байта      — 4058 шагов на байт, 7,83 МЛРД на выгрузку
                              из 5061 записи; проверка не уложилась в
                              полторы минуты и была снята по сроку;
      * без копии, но с
        проверкой значения  —  208 шагов на байт, 402 млн шагов,
                              33,5 СЕКУНДЫ живого времени (замерено на
                              настоящем размере, а не оценено);
      * здесь               — байт только читается, счётчик убавляется.

    Проверка «нет ли перевода строки ВНУТРИ записи» при этом не пропала,
    а переехала туда, где стоит дёшево: общее число байтов 0x0A в файле
    считает вызывающий и сверяет с числом записей. Переводы строки на
    своих местах уже сочтены здесь; если их всего столько же, сколько
    записей, лишних внутри нет. Оба счёта — в байтах.
    """
    # ПЕРВЫЙ БАЙТ ЗАПИСИ ОТДЕЛЁН ОТ ОСТАЛЬНЫХ: он один отвечает на вопрос
    # «запись это или признак конца». Сколько байт идёт до цикла, решает
    # раскладка.
    пролог, (внешний, внутренний) = раскладка(длина)
    хвост = длина - пролог
    п = Сборщик()

    def съесть_если_не_ноль(где: str, флаг: str, пояснение: str) -> None:
        """Не ноль — обнулить ячейку и убавить флаг. Ровно один проход."""
        п.к(где, "к проверяемой ячейке")
        п.код("[[-]" + сдв(где, флаг) + "-" + сдв(флаг, где) + "]", пояснение)

    def перевод_ли_строки(флаг: str, пояснение: str) -> None:
        """Флаг станет единицей тогда и только тогда, когда байт был
        переводом строки. Байт при этом расходуется."""
        п.к("b", "к прочитанному байту")
        п.код("-" * ПЕРЕВОД_СТРОКИ, "вычесть код перевода строки")
        п.к(флаг, "признак совпадения")
        п.код("+", "считаем что совпал")
        съесть_если_не_ноль("b", флаг, пояснение)

    def беда_если(флаг: str, пояснение: str) -> None:
        """Флаг в единице означает беду; флаг расходуется."""
        п.к(флаг, "к признаку")
        п.код("[" + сдв(флаг, "err") + "[-]+" + сдв("err", флаг) + "-]",
              пояснение)

    def отметить() -> None:
        """Печать отметки о записи: точка или восклицательный знак."""
        п.к("t3", "признак годной")
        п.код("+", "считаем что годная")
        п.к("err", "к признаку беды")
        п.код("[", "если с записью беда")
        п.к("out", "к печатаемому")
        п.число("out", ОТМЕТКА_НЕГОДНОЙ, "код восклицательного знака")
        п.код(".", "печать отметки")
        п.код("[-]", "очистить печатаемое")
        п.к("t3", "к признаку годной")
        п.код("-", "не годная")
        п.к("err", "к признаку беды")
        п.код("[-]", "беда учтена")
        п.код("]", "конец ветви беды")
        п.к("t3", "к признаку годной")
        п.код("[", "если беды не было")
        п.к("out", "к печатаемому")
        п.число("out", ОТМЕТКА_ГОДНОЙ, "код точки")
        п.код(".", "печать отметки")
        п.код("[-]", "очистить печатаемое")
        п.к("t3", "к признаку годной")
        п.код("-", "отметка поставлена")
        п.код("]", "конец ветви годной")

    п.код("+", "обработка идёт")
    п.код("[", "пока идёт")

    п.пусто()
    п.речь("  начало записи: вся рабочая часть ленты чистая")
    for имя in ЯЧЕЙКИ:
        if имя == "go":
            continue
        п.к(имя, "очистка")
        п.код("[-]", "обнулить")
    п.к("go", "к началу разметки")

    п.пусто()
    п.речь("  первый байт решает: запись это или признак конца")
    п.к("b", "читаем первый байт")
    п.код(",", "байт с входа")
    п.код("[[-]" + сдв("b", "seen") + "+" + сдв("seen", "b") + "]",
          "байт не ноль значит запись настоящая")

    п.пусто()
    п.речь("  ветвление: настоящая запись или признак конца")
    п.к("t4", "признак конца")
    п.код("+", "считаем что конец")
    п.к("seen", "к признаку записи")
    п.код("[", "если запись настоящая")
    п.к("t4", "к признаку конца")
    п.код("-", "не конец")

    for номер in range(2, пролог + 1):
        п.речь("    байт {} записи: он в цикл не влез".format(номер))
        п.к("b", "читаем байт")
        п.код(",", "байт с входа")

    п.речь("    остальные {} байт: их значения не важны".format(хвост))
    п.к("outer", "внешний счётчик")
    п.число("outer", внешний, "внешних проходов")
    п.код("[", "внешний цикл")
    п.к("inner", "внутренний счётчик")
    п.число("inner", внутренний, "байт за проход")
    п.код("[", "внутренний цикл")
    п.к("b", "читаем байт")
    п.код(",", "байт с входа")
    п.к("inner", "к внутреннему счётчику")
    п.код("-", "байт прочитан")
    п.код("]", "внутренний цикл")
    п.к("outer", "к внешнему счётчику")
    п.код("-", "проход сделан")
    п.код("]", "внешний цикл")

    п.речь("    за записью обязан идти перевод строки")
    п.к("b", "читаем следующий байт")
    п.код(",", "байт с входа")
    перевод_ли_строки("t1", "остаток не ноль значит не перевод строки")
    # Тут условие ОБРАТНОЕ: беда, когда перевода строки НЕТ. Прямо
    # проверить «ноль ли» нельзя — цикл по нулю просто не входит, — и
    # потому берётся второй признак.
    п.к("t2", "признак беды")
    п.код("+", "считаем что беда")
    съесть_если_не_ноль("t1", "t2", "совпал значит беды нет")
    беда_если("t2", "перевода строки на месте нет")

    п.речь("    отметка о записи")
    отметить()

    п.к("seen", "к признаку записи")
    п.код("[-]", "запись обработана")
    п.код("]", "конец ветви настоящей записи")

    п.пусто()
    п.к("t4", "к признаку конца")
    п.код("[", "если первый байт был нулём")
    п.к("go", "к признаку работы")
    п.код("[-]", "обработка кончена")
    п.к("t4", "к признаку конца")
    п.код("-", "учтено")
    п.код("]", "конец ветви признака конца")

    п.к("go", "к началу разметки")
    п.код("]", "пока идёт")

    return п.готово()


def записать(путь: Path, текст: str) -> bool:
    путь.parent.mkdir(parents=True, exist_ok=True)
    новое = текст.encode("utf-8")
    метка = "без изменений"
    if not (путь.exists() and путь.read_bytes() == новое):
        путь.write_bytes(новое)
        метка = "изменён"
    print("  {}  {}".format(путь.relative_to(ROOT).as_posix(), метка))
    return метка == "изменён"


def main() -> int:
    with SRC.open(encoding="utf-8") as f:
        doc = yaml.safe_load(f)
    длина = int(doc["record_bytes"])
    if длина < 2:
        print("длина записи {} бессмысленна".format(длина), file=sys.stderr)
        return 1

    пролог, (внешний, внутренний) = раскладка(длина)
    текст = (заголовок(длина, пролог, внешний, внутренний) + "\n"
             + собрать(длина))

    команд = sum(1 for c in текст if c in КОМАНДЫ)
    изменено = записать(OUT, текст)
    print("запись {} байт: {} до цикла и {} на {} в цикле; "
          "команд {}, файлов изменено: {}"
          .format(длина, пролог, внешний, внутренний, команд, int(изменено)))
    return 0


